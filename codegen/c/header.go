package c

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/tacklang/tack/ast"
)

// HeaderName is the name of the header the C files of a program include:
// the driver writes Header's output under it.
const HeaderName = "tack.h"

// Header returns tack.h for prog, which must have been generated without
// diagnostics: the C declarations the C files linked with prog compile
// against, a prototype for every extern func under its C name, package by
// package, so clang checks each C definition against its Tack declaration,
// with that declaration in a comment beside it.
func (backend) Header(prog *ast.Program) []byte {
	var b bytes.Buffer
	b.WriteString("// Generated by the Tack compiler. Do not edit.\n//\n")
	b.WriteString("// It declares every extern func of the program, for the C files that\n")
	b.WriteString("// define them.\n\n")
	b.WriteString("#ifndef TACK_H\n#define TACK_H\n\n")
	b.WriteString("#include <stdbool.h>\n#include <stdint.h>\n")
	for _, pkg := range prog.Packages {
		var protos []string
		for _, decl := range pkg.Decls() {
			if fn, ok := decl.(*ast.Func); ok && fn.Extern {
				protos = append(protos, cPrototype(fn)+" // "+tackSignature(prog, fn))
			}
		}
		if len(protos) > 0 {
			fmt.Fprintf(&b, "\n// package %s\n%s\n", pkg.Path, strings.Join(protos, "\n"))
		}
	}
	b.WriteString("\n#endif\n")
	return b.Bytes()
}

// tackSignature is fn's declaration as Tack writes it, without its
// visibility, which tack.h shows beside its prototype, so a clang error
// that quotes the prototype also shows what it declares.
func tackSignature(prog *ast.Program, fn *ast.Func) string {
	params := make([]string, len(fn.Params))
	for i, p := range fn.Params {
		params[i] = p.Name + " " + prog.Types.Name(p.Type)
	}
	results := make([]string, len(fn.ResultTypes))
	for i, r := range fn.ResultTypes {
		results[i] = prog.Types.Name(r)
	}
	sig := fmt.Sprintf("extern func %s(%s)", fn.Name, strings.Join(params, ", "))
	switch len(results) {
	case 0:
		return sig
	case 1:
		return sig + " " + results[0]
	default:
		return sig + " (" + strings.Join(results, ", ") + ")"
	}
}

// cPrototype is the prototype of fn, an extern func, as tack.h declares
// it: its C name, and the C type of each parameter and result, without
// the parameters' names, which could be C keywords or tack.h's type names.
func cPrototype(fn *ast.Func) string {
	result := "void"
	if len(fn.ResultTypes) == 1 {
		result = basicCType(fn.ResultTypes[0])
	}
	params := make([]string, len(fn.Params))
	for i, p := range fn.Params {
		params[i] = basicCType(p.Type)
	}
	if len(params) == 0 {
		params = []string{"void"}
	}
	return fmt.Sprintf("%s %s(%s);", result, fn.CName, strings.Join(params, ", "))
}
