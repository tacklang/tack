package c

import (
	"bytes"
	"fmt"
	"math"
	"strconv"
	"strings"

	"github.com/tacklang/tack/ast"
	"github.com/tacklang/tack/builtin"
	"github.com/tacklang/tack/codegen"
	"github.com/tacklang/tack/diag"
	"github.com/tacklang/tack/types"
)

func init() { codegen.Register(New()) }

type backend struct{}

// New returns the C code generation backend.
func New() codegen.Backend { return backend{} }

func (backend) Name() string { return "c" }

func (backend) Ext() string { return ".c" }

func (backend) BuildCmd(src, out string) []string { return []string{"clang", "-o", out, src} }

func (backend) Generate(file *ast.File) ([]byte, []diag.Diagnostic) {
	g := &generator{file: file, globals: make(map[*ast.Var]bool)}
	return g.generate()
}

// str is one entry in the string pool: the C identifier it is emitted under
// and the bytes it holds.
type str struct {
	label string
	value string
}

type generator struct {
	file    *ast.File
	strPool []str
	globals map[*ast.Var]bool // the package-level variables
	buf     bytes.Buffer
}

func (g *generator) generate() ([]byte, []diag.Diagnostic) {
	// The pool is filled first: generating a body needs the label of every
	// string it mentions. The newline print appends goes in before any
	// literal, so it is always str0 when present, and only when something
	// prints, so a program that does not carries no unused constant.
	if g.printsAnything() {
		g.addStr("\n")
	}
	g.collectStrings()

	// Globals are known before any body is generated, since a body names a
	// global differently from a local.
	for _, decl := range g.file.Decls {
		if v, ok := decl.(*ast.Var); ok {
			g.globals[v] = true
		}
	}

	// Everything is generated before anything is written, so a construct the
	// backend cannot lower produces a diagnostic instead of a half-written
	// file.
	globals, funcs, bodies, diags := g.generateDecls()
	if len(diags) > 0 {
		return nil, diags
	}

	g.emitPreamble()
	g.emitConstantPool()
	g.emitGlobals(globals)
	g.emitPrototypes()

	for i, fn := range funcs {
		g.emitFunc(fn, bodies[i])
	}

	g.emitEntryPoint()

	return g.buf.Bytes(), nil
}

func (g *generator) emitPreamble() {
	g.buf.WriteString("// Generated by the Tack compiler. Do not edit.\n\n")
	g.buf.WriteString("#include <stdbool.h>\n")
	g.buf.WriteString("#include <stdint.h>\n")
	g.buf.WriteString("#include <stdio.h>\n")
	g.buf.WriteString("#include <stdlib.h>\n\n")

	// A Tack string is one value that happens to occupy two words, so it is
	// one struct rather than a pointer and a length passed separately. That is
	// what lets it be returned, stored, and nested later without changing
	// every signature that mentions it.
	g.buf.WriteString("typedef struct {\n")
	g.buf.WriteString("    const unsigned char *ptr;\n")
	g.buf.WriteString("    int64_t len;\n")
	g.buf.WriteString("} tack_string;\n\n")
}

// collectStrings pools every string literal in the file, deduplicated, and
// the empty string if a string variable starts from its zero value.
func (g *generator) collectStrings() {
	ast.Walk(g.file, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.StrLit:
			g.addStr(x.Value)
		case *ast.Var:
			if x.Value == nil && x.Kind == types.String {
				g.addStr("")
			}
		}
		return true
	})
}

// emitConstantPool writes the pooled strings as byte arrays. Bytes rather than
// C string literals so that any byte survives without an escaping scheme, and
// a trailing zero so an empty literal is still a legal array; the zero is
// never written out, since every write is length-bounded.
func (g *generator) emitConstantPool() {
	for _, s := range g.strPool {
		fmt.Fprintf(&g.buf, "static const unsigned char %s[%d] = {%s};\n",
			s.label, len(s.value)+1, g.toBytes(s.value))
	}

	g.buf.WriteString("\n")

	// print goes through one helper so that a literal and a parameter take the
	// same path. Emitted only when the program prints, so an unused static
	// function never reaches the C compiler.
	if g.printsAnything() {
		g.buf.WriteString("static void tack_print(tack_string s) {\n")
		g.buf.WriteString("    fwrite(s.ptr, 1, s.len, stdout);\n")
		g.buf.WriteString("}\n\n")
	}
}

func (g *generator) printsAnything() bool {
	prints := false
	ast.Walk(g.file, func(n ast.Node) bool {
		if call, ok := n.(*ast.Call); ok {
			if id, ok := call.Fn.(*ast.Ident); ok && id.Name == "print" {
				prints = true
			}
		}
		return true
	})
	return prints
}

// generateDecls generates every top-level declaration: each global as one
// line of C, and each function's body, returned alongside the functions in
// source order.
func (g *generator) generateDecls() (
	globals []string,
	funcs []*ast.Func,
	bodies [][]string,
	diags []diag.Diagnostic,
) {
	for _, decl := range g.file.Decls {
		switch d := decl.(type) {
		case *ast.Var:
			global, diags := g.generateGlobal(d)
			if len(diags) > 0 {
				return nil, nil, nil, diags
			}
			globals = append(globals, global)

		case *ast.Func:
			body, diags := g.generateFuncBody(d)
			if len(diags) > 0 {
				return nil, nil, nil, diags
			}
			funcs = append(funcs, d)
			bodies = append(bodies, body)

		default:
			return nil, nil, nil, []diag.Diagnostic{{
				Severity: diag.Error,
				Message:  fmt.Sprintf("unknown declaration type: %T", decl),
				Span:     decl.Spanned(),
			}}
		}
	}
	return globals, funcs, bodies, nil
}

// emitGlobals writes the package-level variable declarations.
func (g *generator) emitGlobals(globals []string) {
	if len(globals) == 0 {
		return
	}
	for _, global := range globals {
		g.buf.WriteString(global + "\n")
	}
	g.buf.WriteString("\n")
}

// generateGlobal declares a package-level variable as a static C variable,
// const unless it is mutable, initialized with the value the type checker
// computed rather than its source expression. The checker has already ruled
// out overflow and division by zero, so the value is exactly what Tack means.
func (g *generator) generateGlobal(v *ast.Var) (string, []diag.Diagnostic) {
	value, ok := g.constValue(v.Const)
	if !ok {
		return "", []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("package-level variable %s has no computed value", v.Name),
			Span:     v.NameSpan,
		}}
	}

	qualifier := "static const"
	if v.Mutable {
		qualifier = "static"
	}
	return fmt.Sprintf("%s %s %s = %s;", qualifier, cType(v.Kind), g.mangle(v.Name), value), nil
}

// constValue renders a computed constant as a C constant expression, usable
// to initialize a static variable. The smallest int64 is written as an
// expression, since C has no literal for it: the literal after the minus
// sign would not fit.
func (g *generator) constValue(c any) (string, bool) {
	switch v := c.(type) {
	case int64:
		if v == math.MinInt64 {
			return "(-9223372036854775807 - 1)", true
		}
		return strconv.FormatInt(v, 10), true
	case bool:
		return strconv.FormatBool(v), true
	case string:
		return fmt.Sprintf("{%s, %d}", g.strLabel(v), len(v)), true
	default:
		return "", false
	}
}

// emitPrototypes forward declares every Tack function. Tack lets a function
// call one declared later in the file; C does not, without a prototype.
func (g *generator) emitPrototypes() {
	if len(g.file.Decls) == 0 {
		return
	}

	for _, decl := range g.file.Decls {
		if fn, ok := decl.(*ast.Func); ok {
			g.buf.WriteString(g.signature(fn) + ";\n")
		}
	}

	g.buf.WriteString("\n")
}

func (g *generator) emitFunc(fn *ast.Func, body []string) {
	g.buf.WriteString(g.signature(fn) + " {\n")
	if len(body) > 0 {
		fmt.Fprintf(&g.buf, "    %s\n", strings.Join(body, "\n    "))
	}
	g.buf.WriteString("}\n\n")
}

// emitEntryPoint writes C's main, which exists only to call Tack's.
func (g *generator) emitEntryPoint() {
	g.buf.WriteString("int main(void) {\n")
	fmt.Fprintf(&g.buf, "    %s();\n", g.mangle("main"))
	g.buf.WriteString("    return 0;\n")
	g.buf.WriteString("}\n")
}

func (g *generator) signature(fn *ast.Func) string {
	result := "void"
	if fn.Result != nil {
		result = cType(fn.ResultKind)
	}

	if len(fn.Params) == 0 {
		return fmt.Sprintf("static %s %s(void)", result, g.mangle(fn.Name))
	}

	params := make([]string, len(fn.Params))
	for i, param := range fn.Params {
		params[i] = fmt.Sprintf("%s %s", cType(param.Kind), paramName(param.Name))
	}
	return fmt.Sprintf("static %s %s(%s)", result, g.mangle(fn.Name), strings.Join(params, ", "))
}

func (g *generator) generateFuncBody(fn *ast.Func) ([]string, []diag.Diagnostic) {
	return g.generateBlock(fn.Body, fn)
}

func (g *generator) generateBlock(body []ast.Stmt, fn *ast.Func) ([]string, []diag.Diagnostic) {
	lines := make([]string, 0)

	for _, stmt := range body {
		got, diags := g.generateStmt(stmt, fn)
		if len(diags) > 0 {
			return nil, diags
		}
		lines = append(lines, got...)
	}

	return lines, nil
}

func (g *generator) generateStmt(stmt ast.Stmt, fn *ast.Func) ([]string, []diag.Diagnostic) {
	switch x := stmt.(type) {
	case *ast.Return:
		if x.Value == nil {
			return []string{"return;"}, nil
		}

		value, diags := g.expr(x.Value, fn.ResultKind)
		if len(diags) > 0 {
			return nil, diags
		}
		return []string{fmt.Sprintf("return %s;", value)}, nil

	case *ast.If:
		return g.generateIf(x, fn)

	case *ast.Var:
		return g.generateVar(x)

	case *ast.Assign:
		return g.generateAssign(x)

	case *ast.ExprStmt:
		return g.generateExprStmt(x)

	default:
		return nil, []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("unknown statement type: %T", stmt),
			Span:     stmt.Spanned(),
		}}
	}
}

func (g *generator) generateIf(stmt *ast.If, fn *ast.Func) ([]string, []diag.Diagnostic) {
	cond, diags := g.expr(stmt.Cond, types.Bool)
	if len(diags) > 0 {
		return nil, diags
	}

	then, diags := g.generateBlock(stmt.Then, fn)
	if len(diags) > 0 {
		return nil, diags
	}

	// A binary expression is already parenthesised, and a second pair makes
	// clang warn about an equality test, so it only gets the if's own.
	header := fmt.Sprintf("if (%s) {", cond)
	if _, ok := stmt.Cond.(*ast.Binary); ok {
		header = fmt.Sprintf("if %s {", cond)
	}

	lines := append([]string{header}, indent(then)...)

	if stmt.Else == nil {
		return append(lines, "}"), nil
	}

	els, diags := g.generateBlock(stmt.Else, fn)
	if len(diags) > 0 {
		return nil, diags
	}

	lines = append(lines, "} else {")
	lines = append(lines, indent(els)...)
	return append(lines, "}"), nil
}

// generateAssign sets a local to a new value.
func (g *generator) generateAssign(a *ast.Assign) ([]string, []diag.Diagnostic) {
	value, diags := g.expr(a.Value, ast.KindOf(a.Value))
	if len(diags) > 0 {
		return nil, diags
	}
	target, ok := a.Target.Def.(*ast.Var)
	if !ok {
		return nil, []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("cannot assign to %s", a.Target.Name),
			Span:     a.Target.Span,
		}}
	}
	return []string{fmt.Sprintf("%s = %s;", g.varRef(target), value)}, nil
}

// generateExprStmt lowers an expression statement, which can only be a call
// to a named function today.
func (g *generator) generateExprStmt(stmt *ast.ExprStmt) ([]string, []diag.Diagnostic) {
	call, ok := stmt.X.(*ast.Call)
	if !ok {
		return nil, []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("unknown expression type: %T", stmt.X),
			Span:     stmt.Spanned(),
		}}
	}

	id, ok := call.Fn.(*ast.Ident)
	if !ok {
		return nil, []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("unknown expression type: %T", call.Fn),
			Span:     stmt.Spanned(),
		}}
	}

	return g.generateCall(id.Name, call)
}

// generateVar declares a local. An immutable variable becomes a const C
// local, so the C compiler holds it to the same rule. A variable without a
// value starts from its type's zero value.
func (g *generator) generateVar(v *ast.Var) ([]string, []diag.Diagnostic) {
	value := g.zeroValue(v.Kind)
	if v.Value != nil {
		expr, diags := g.expr(v.Value, v.Kind)
		if len(diags) > 0 {
			return nil, diags
		}
		value = expr
	}

	decl := fmt.Sprintf("%s %s = %s;", cType(v.Kind), varName(v.Name), value)
	if !v.Mutable {
		decl = "const " + decl
	}
	return []string{decl}, nil
}

// zeroValue is the C expression for a type's zero value. The empty string
// points at a pooled empty array rather than NULL, so writing it never hands
// libc a null pointer.
func (g *generator) zeroValue(kind types.Kind) string {
	switch kind {
	case types.String:
		return g.stringValue("")
	case types.Bool:
		return "false"
	default:
		return "0"
	}
}

// indent shifts a nested block one level right. Function bodies are emitted at
// one level already, so this is what keeps branches readable.
func indent(lines []string) []string {
	out := make([]string, len(lines))
	for i, line := range lines {
		out[i] = "    " + line
	}
	return out
}

func (g *generator) generateCall(name string, call *ast.Call) ([]string, []diag.Diagnostic) {
	switch name {
	case "print":
		var lines []string
		for _, a := range call.Args {
			expr, diags := g.expr(a, types.String)
			if len(diags) > 0 {
				return nil, diags
			}
			lines = append(lines,
				fmt.Sprintf("tack_print(%s);", expr),
				fmt.Sprintf("tack_print(%s);", g.stringValue("\n")))
		}
		return lines, nil

	case "exit":
		var lines []string
		for _, a := range call.Args {
			expr, diags := g.expr(a, types.Int)
			if len(diags) > 0 {
				return nil, diags
			}
			lines = append(lines, fmt.Sprintf("exit(%s);", expr))
		}
		return lines, nil

	default:
		expr, diags := g.callExpr(name, call)
		if len(diags) > 0 {
			return nil, diags
		}
		return []string{expr + ";"}, nil
	}
}

// callExpr renders a call to a declared function as a C expression.
func (g *generator) callExpr(name string, call *ast.Call) (string, []diag.Diagnostic) {
	args := make([]string, len(call.Args))
	for i, a := range call.Args {
		expr, diags := g.expr(a, ast.KindOf(a))
		if len(diags) > 0 {
			return "", diags
		}
		args[i] = expr
	}
	return fmt.Sprintf("%s(%s)", g.mangle(name), strings.Join(args, ", ")), nil
}

// expr renders an expression as C. want is the type the context requires;
// passing types.Invalid means any type the expression happens to have.
func (g *generator) expr(e ast.Expr, want types.Kind) (string, []diag.Diagnostic) {
	if got := ast.KindOf(e); got != want && want != types.Invalid {
		return "", []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("cannot use %s as %s", got, want),
			Span:     e.Spanned(),
		}}
	}

	switch x := e.(type) {
	case *ast.IntLit:
		return strconv.FormatInt(x.Value, 10), nil
	case *ast.StrLit:
		return g.stringValue(x.Value), nil
	case *ast.BoolLit:
		return strconv.FormatBool(x.Value), nil
	case *ast.Ident:
		return g.identExpr(x)
	case *ast.Binary:
		return g.binaryExpr(x)
	case *ast.Call:
		return g.callValue(x)
	default:
		return "", []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("unknown expression type: %T", e),
			Span:     e.Spanned(),
		}}
	}
}

// identExpr renders a reference to a parameter or variable as the C name it
// was declared under.
func (g *generator) identExpr(id *ast.Ident) (string, []diag.Diagnostic) {
	switch def := id.Def.(type) {
	case *ast.Param:
		return paramName(def.Name), nil
	case *ast.Var:
		return g.varRef(def), nil
	default:
		return "", []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("unbound identifier: %s", id.Name),
			Span:     id.Span,
		}}
	}
}

// binaryExpr renders an infix operation as C.
func (g *generator) binaryExpr(bin *ast.Binary) (string, []diag.Diagnostic) {
	left, diags := g.expr(bin.X, types.Invalid)
	if len(diags) > 0 {
		return "", diags
	}
	right, diags := g.expr(bin.Y, types.Invalid)
	if len(diags) > 0 {
		return "", diags
	}
	// Parenthesised so that Tack's grouping survives regardless of how C
	// would have parsed the same operators.
	return fmt.Sprintf("(%s %s %s)", left, bin.Op, right), nil
}

// callValue renders a call used where a value is wanted, rejecting a callee
// that is not a plain name and a builtin, which has no value to give.
func (g *generator) callValue(call *ast.Call) (string, []diag.Diagnostic) {
	id, ok := call.Fn.(*ast.Ident)
	if !ok {
		return "", []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("unknown expression type: %T", call.Fn),
			Span:     call.Spanned(),
		}}
	}
	if _, isBuiltin := builtin.Lookup(id.Name); isBuiltin {
		return "", []diag.Diagnostic{{
			Severity: diag.Error,
			Message:  fmt.Sprintf("%s returns no value", id.Name),
			Span:     call.Spanned(),
		}}
	}
	return g.callExpr(id.Name, call)
}

// stringValue is a string literal as a tack_string value.
func (g *generator) stringValue(s string) string {
	return fmt.Sprintf("(tack_string){%s, %d}", g.strLabel(s), len(s))
}

func cType(kind types.Kind) string {
	switch kind {
	case types.Int:
		return "int64_t"
	case types.String:
		return "tack_string"
	case types.Bool:
		return "bool"
	default:
		return "void"
	}
}

// paramName keeps parameters clear of every other name the generated file
// defines. Tack has no reserved words, so a parameter may legally be called
// str0, exit, or int, each of which collides with something already emitted.
func paramName(name string) string { return "p_" + name }

// varRef is the C name of a variable: the mangled package-level name for a
// global, the prefixed local name otherwise.
func (g *generator) varRef(v *ast.Var) string {
	if g.globals[v] {
		return g.mangle(v.Name)
	}
	return varName(v.Name)
}

// varName keeps local variables clear of every other name the generated file
// defines, for the same reason paramName does. The distinct prefix keeps a
// variable and a parameter apart even if Tack ever let them share a name.
func varName(name string) string { return "v_" + name }

// mangle turns a Tack function name into a C identifier. Tack's package-scoped
// names contain a dot, which C does not allow. This is unambiguous only while
// package names cannot contain an underscore; the language has one package.
func (g *generator) mangle(name string) string {
	return fmt.Sprintf("tack_%s_%s", g.file.Package, name)
}

func (g *generator) seenStr(s string) bool {
	for _, x := range g.strPool {
		if x.value == s {
			return true
		}
	}
	return false
}

func (g *generator) addStr(s string) {
	if g.seenStr(s) {
		return
	}
	g.strPool = append(g.strPool, str{fmt.Sprintf("str%d", len(g.strPool)), s})
}

func (g *generator) strLabel(s string) string {
	for _, x := range g.strPool {
		if x.value == s {
			return x.label
		}
	}
	return ""
}

// toBytes renders s as C array initialiser bytes, with the trailing zero that
// emitConstantPool's declared length accounts for.
func (g *generator) toBytes(s string) string {
	parts := make([]string, len(s)+1)
	for i := 0; i < len(s); i++ {
		parts[i] = strconv.Itoa(int(s[i]))
	}
	parts[len(s)] = "0"
	return strings.Join(parts, ", ")
}
