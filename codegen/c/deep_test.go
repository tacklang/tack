// update rewrites examples/deep-expressions/main.tck from deepProgram.
var update = flag.Bool("update", false, "rewrite examples/deep-expressions/main.tck")

// deepSizes says how long and how deep each shape deepProgram writes is.
type deepSizes struct {
	chain int // terms of each chain of + - and *, and of the order checks
	calls int // nested calls
	unary int // nested unary minuses
	logic int // terms of each && and || chain
}

// exampleSizes are the sizes of examples/deep-expressions: each nests
// past maxDepth in C, so every way of holding a deep part runs, and the
// chains wrap the narrow types, while the example stays small, since the
// parser's tests parse every example once per token. bigSizes, which
// only tests write, are what C could not parse.
var exampleSizes = deepSizes{chain: 20, calls: 36, unary: 36, logic: 36}

// bigSizes are the sizes TestDeepExpressionsRun checks at every
// optimization level: each far past where clang ran out of stack on the C
// the backend wrote before it held deep parts in temporaries, 287 terms of
// +, 283 minuses, 1883 nested calls and 1200 terms of &&.
var bigSizes = deepSizes{chain: 2000, calls: 2500, unary: 1000, logic: 2500}

// intType is one of Tack's sized integer types, which wrap.
type intType struct {
	name   string
	bits   int
	signed bool
}

// intTypes are the sized integer types, each of which a chain is written
// in.
var intTypes = []intType{
	{"int8", 8, true},
	{"int16", 16, true},
	{"int32", 32, true},
	{"int64", 64, true},
	{"uint8", 8, false},
	{"uint16", 16, false},
	{"uint32", 32, false},
	{"uint64", 64, false},
}

// wrap returns v kept to t's width, as Tack's arithmetic leaves it, as a
// Tack literal of t: the low bits, read as signed for a signed t.
func (t intType) wrap(v uint64) string {
	if t.bits < 64 {
		v &= 1<<t.bits - 1
	}
	if !t.signed {
		return strconv.FormatUint(v, 10)
	}
	if v>>(t.bits-1)&1 == 1 {
		return strconv.FormatInt(int64(v|^uint64(0)<<(t.bits-1)), 10)
	}
	return strconv.FormatUint(v, 10)
}

// joined returns n copies of term joined by op, a chain C nests one level
// per operator.
func joined(term, op string, n int) string {
	return strings.Repeat(term+" "+op+" ", n-1) + term
}

// rightNested returns n copies of term, each the left operand of op and
// a parenthesized rest: term op (term op (... term)).
func rightNested(term, op string, n int) string {
	return strings.Repeat(term+" "+op+" (", n-1) + term + strings.Repeat(")", n-1)
}

// pow returns b to the power n, wrapping at 64 bits.
func pow(b uint64, n int) uint64 {
	r := uint64(1)
	for range n {
		r *= b
	}
	return r
}

// deepWriter writes the program deepProgram returns: its declarations,
// and the checks its main makes, in order.
type deepWriter struct {
	b      strings.Builder
	checks []string
	s      deepSizes
}

// decl writes a declaration, formatted as fmt.Sprintf formats it, and a
// blank line after it.
func (d *deepWriter) decl(format string, args ...any) {
	fmt.Fprintf(&d.b, format+"\n\n", args...)
}

// check adds a check of cond, a Tack condition, named name, to main.
func (d *deepWriter) check(cond, name string) {
	d.checks = append(d.checks, fmt.Sprintf("check(%s, %q)", cond, name))
}

// deepProgram returns a program that computes, and checks, expressions
// nested as deeply as s says, in every shape and place that keeps an
// expression's parts in one C expression: chains of + - and * of every
// sized integer type, wrapping, left and right nested; mixed operators
// with division; nested calls and unary minuses; chains whose parts run
// in order around calls that change what other parts read; && and ||
// chains, and a chain inside the right side of && that must not run when
// the left side is false; and chains in a loop's condition, a defer, a
// return of two results, a struct literal, an element assignment and a
// checked index. Each check prints its name and "ok", or "FAIL".
func deepProgram(s deepSizes) string {
	d := &deepWriter{s: s}
	d.b.WriteString("package main\n\n" +
		"// Expressions nested deeper than C compilers parse, generated by\n" +
		"// deepProgram in codegen/c/deep_test.go: each check prints its name and\n" +
		"// ok when the value computed is the one Tack defines, wrapping included.\n\n")
	d.decl("type Pair struct {\n    a int64\n    b int64\n}")
	d.decl("func check(cond bool, name string) {\n    print(name)\n    if cond {\n" +
		"        print(\" ok\\n\")\n    } else {\n        print(\" FAIL\\n\")\n    }\n}")
	d.decl("func inc(v int64) int64 {\n    return v + 1\n}")
	d.decl("func sub(a int64, b int64) int64 {\n    return a - b\n}")
	d.decl("func tick(mut c int64) int64 {\n    c += 1\n    return c\n}")
	for _, t := range intTypes {
		d.chains(t)
	}
	d.mixed()
	d.mixedRight()
	d.calls()
	d.order()
	d.logic()
	d.places()
	d.b.WriteString("func main() {\n")
	for _, ch := range d.checks {
		d.b.WriteString("    " + ch + "\n")
	}
	d.b.WriteString("}\n")
	return d.b.String()
}

// chains writes chains of + - and * of type t, left nested, each of
// s.chain terms, and checks each wraps as t does; for a 64-bit t, also
// one of +, right nested. The chains of + and - add 100 each time, and
// of * multiply by 3, so even short ones wrap the narrow types.
func (d *deepWriter) chains(t intType) {
	n := d.s.chain
	bodies := []struct{ name, body string }{
		{"add", joined("x", "+", n)},
		{"minus", joined("x", "-", n)},
		{"times", joined("x", "*", n)},
	}
	if t.bits == 64 {
		bodies = append(bodies, struct{ name, body string }{"right", rightNested("x", "+", n)})
	}
	for _, f := range bodies {
		d.decl("func %s_%s(x %s) %s {\n    return %s\n}", f.name, t.name, t.name, t.name, f.body)
	}
	u := uint64(n)
	d.check(
		fmt.Sprintf("add_%s(100) == %s", t.name, t.wrap(100*u)),
		fmt.Sprintf("%d terms of + in %s", n, t.name),
	)
	d.check(
		fmt.Sprintf("minus_%s(100) == %s", t.name, t.wrap(100-100*(u-1))),
		fmt.Sprintf("%d terms of - in %s", n, t.name),
	)
	d.check(
		fmt.Sprintf("times_%s(3) == %s", t.name, t.wrap(pow(3, n))),
		fmt.Sprintf("%d terms of * in %s", n, t.name),
	)
	if t.bits == 64 {
		d.check(fmt.Sprintf("right_%s(3) == %s", t.name, t.wrap(3*u)),
			fmt.Sprintf("%d right-nested terms of + in %s", n, t.name))
	}
}

// mixedSteps are the operations mixed applies in turn, as Tack writes
// them and as Go computes them on an int64, which wraps and truncates as
// Tack's does.
var mixedSteps = []struct {
	do   func(int64) int64
	tack string
}{
	{func(v int64) int64 { return v + 7 }, "+ 7"},
	{func(v int64) int64 { return v * 3 }, "* 3"},
	{func(v int64) int64 { return v - 11 }, "- 11"},
	{func(v int64) int64 { return v / 2 }, "/ 2"},
	{func(v int64) int64 { return v % 1000003 }, "% 1000003"},
}

// mixed writes a left-nested chain of mixedSteps, applied in turn, twice
// as long as the other chains: a division nests less in C than the other
// operators do.
func (d *deepWriter) mixed() {
	expr, v := "x", int64(5)
	for i := range 2*d.s.chain - 1 {
		step := mixedSteps[i%len(mixedSteps)]
		expr = "(" + expr + " " + step.tack + ")"
		v = step.do(v)
	}
	d.decl("func mixed(x int64) int64 {\n    return %s\n}", expr)
	d.check(fmt.Sprintf("mixed(5) == %d", v), fmt.Sprintf("%d mixed operators", 2*d.s.chain))
}

// mixedRight writes x * (x - (x + (x * ...))), right nested.
func (d *deepWriter) mixedRight() {
	expr, v := "x", int64(2)
	for i := d.s.chain - 2; i >= 0; i-- {
		switch i % 3 {
		case 0:
			expr, v = "x * ("+expr+")", 2*v
		case 1:
			expr, v = "x - ("+expr+")", 2-v
		default:
			expr, v = "x + ("+expr+")", 2+v
		}
	}
	d.decl("func mixed_right(x int64) int64 {\n    return %s\n}", expr)
	d.check(
		fmt.Sprintf("mixed_right(2) == %d", v),
		fmt.Sprintf("%d right-nested mixed operators", d.s.chain),
	)
}

// calls writes calls nested through the first argument and through the
// second, and minuses nested.
func (d *deepWriter) calls() {
	n := d.s.calls
	d.decl(
		"func calls(x int64) int64 {\n    return %s\n}",
		strings.Repeat("inc(", n)+"x"+strings.Repeat(")", n),
	)
	d.decl("func calls_right(x int64) int64 {\n    return %s\n}",
		strings.Repeat("sub(x, ", n)+"0"+strings.Repeat(")", n))
	right := int64(0)
	for range n {
		right = 4 - right
	}
	d.check(fmt.Sprintf("calls(1) == %d", 1+n), fmt.Sprintf("%d nested calls", n))
	d.check(
		fmt.Sprintf("calls_right(4) == %d", right),
		fmt.Sprintf("%d calls nested in the second argument", n),
	)

	neg := int64(9)
	if d.s.unary%2 == 1 {
		neg = -9
	}
	d.decl("func negated(x int64) int64 {\n    return %s\n}",
		strings.Repeat("-(", d.s.unary)+"x"+strings.Repeat(")", d.s.unary))
	d.check(fmt.Sprintf("negated(9) == %d", neg), fmt.Sprintf("%d nested minuses", d.s.unary))
}

// orderParts returns 2*s.chain terms that read c and tick it, in turn,
// twice as many as the other chains have, since a call nests less in C
// than an operator does, and what their sum is, and c after them, when
// they run left to right.
func (d *deepWriter) orderParts() (parts []string, sum, c int64) {
	parts = make([]string, 2*d.s.chain)
	for i := range parts {
		parts[i] = "c"
		if i%2 == 1 {
			parts[i] = "tick(mut c)"
			c++
		}
		sum += c
	}
	return parts, sum, c
}

// order writes chains that read c and change it, left and right nested,
// whose sum shows every part ran in its place, and one as the right side
// of &&, which runs only when the left side is true.
func (d *deepWriter) order() {
	parts, sum, c := d.orderParts()
	left := strings.Join(parts, " + ")
	right := strings.Join(parts, " + (") + strings.Repeat(")", len(parts)-1)
	d.decl("func order_left() int64 {\n    mut c int64 = 0\n    return %s\n}", left)
	d.decl("func order_right() int64 {\n    mut c int64 = 0\n    return %s\n}", right)
	d.decl("func guarded(run bool) int64 {\n    mut c int64 = 0\n    if run && %s > 0 {\n"+
		"        return c\n    }\n    return c\n}", left)
	d.check(
		fmt.Sprintf("order_left() == %d", sum),
		fmt.Sprintf("%d terms run left to right", 2*d.s.chain),
	)
	d.check(
		fmt.Sprintf("order_right() == %d", sum),
		fmt.Sprintf("%d right-nested terms run left to right", 2*d.s.chain),
	)
	d.check("guarded(false) == 0", "a deep right side of && does not run")
	d.check(fmt.Sprintf("guarded(true) == %d", c), "a deep right side of && runs")
}

// logic writes && and || chains of s.logic terms, with a tick in the
// middle that runs only when every term before it does.
func (d *deepWriter) logic() {
	half, n := d.s.logic/2, d.s.logic
	ands := joined(
		"x > 0",
		"&&",
		half,
	) + " && tick(mut c) > 0 && " + joined(
		"x > 0",
		"&&",
		n-half-1,
	)
	ors := joined("x < 0", "||", half) + " || tick(mut c) < 0 || " + joined("x < 0", "||", n-half-1)
	d.decl(
		"func ands(x int64) int64 {\n    mut c int64 = 0\n    if %s {\n        return c + 10\n    }\n    return c\n}",
		ands,
	)
	d.decl(
		"func ors(x int64) int64 {\n    mut c int64 = 0\n    if %s {\n        return c + 10\n    }\n    return c\n}",
		ors,
	)
	d.check("ands(1) == 11", fmt.Sprintf("%d terms of && hold", n))
	d.check("ands(-1) == 0", fmt.Sprintf("%d terms of && stop at the first", n))
	d.check("ors(1) == 1", fmt.Sprintf("%d terms of || fail", n))
	d.check("ors(-1) == 10", fmt.Sprintf("%d terms of || stop at the first", n))
}

// places writes chains in a loop's condition, once with a tick each time
// it is tested, a defer, a return of two results, a struct literal, an
// element assigned and a checked index, in range and out of it.
func (d *deepWriter) places() {
	n := int64(d.s.chain)
	chain := joined("x", "+", d.s.chain)
	d.decl(
		"func looped(x int64) int64 {\n    mut i int64 = 0\n    for %s + i < %d {\n        i += 1\n    }\n"+
			"    return i\n}",
		chain,
		3*n+4,
	)
	d.decl(
		"func ticked(x int64) int64 {\n    mut c int64 = 0\n    mut n int64 = 0\n    for tick(mut c) + %s < %d {\n"+
			"        n += 1\n    }\n    return n * 100 + c\n}",
		chain,
		3*n+5,
	)
	d.decl(
		"func deferred(x int64) int64 {\n    defer {\n        check(%s == %d, \"a deep defer\")\n    }\n"+
			"    return x\n}",
		chain,
		3*n,
	)
	d.decl(
		"func two(x int64) (int64, int64) {\n    return %s, %s\n}",
		chain,
		joined("x", "-", d.s.chain),
	)
	d.decl(
		"func paired(x int64) Pair {\n    return Pair{a: %s, b: %s}\n}",
		chain,
		joined("x", "*", 3),
	)
	d.decl(
		"func indexed(x uint8) int64 {\n    mut a [256]int64\n    for i := range a {\n        a[i] = i * 2\n    }\n"+
			"    a[x] = %s\n    return a[x]\n}",
		joined("a[x]", "+", d.s.chain),
	)
	d.decl(
		"func checked(x int64) (int64, bool) {\n    a := [4]int64{10, 20, 30, 40}\n    v, ok := a[%s - %d]\n"+
			"    return v, ok\n}",
		chain,
		3*n-2,
	)
	d.decl(
		"func both(x int64) bool {\n    a, b := two(x)\n    return a == %d && b == %d\n}",
		3*n,
		3-3*(n-1),
	)
	d.decl("func in_range() bool {\n    v, ok := checked(3)\n    return ok && v == 30\n}")
	d.decl("func out_of_range() bool {\n    v, ok := checked(4)\n    return !ok && v == 0\n}")
	d.check("looped(3) == 4", "a deep loop condition")
	d.check("ticked(3) == 405", "a deep loop condition with a call, tested five times")
	d.check("deferred(3) == 3", "a deep defer's function returns")
	d.check("both(3)", "two deep results")
	d.check(
		fmt.Sprintf("paired(3).a == %d && paired(3).b == 27", 3*n),
		"a deep struct literal field",
	)
	d.check(fmt.Sprintf("indexed(3) == %d", 6*n), "a deep chain of elements, assigned to one")
	d.check("in_range()", "a deep checked index in range")
	d.check("out_of_range()", "a deep checked index out of range")
}

// deepChecks is how many checks deepProgram's program prints.
func deepChecks() int {
	return strings.Count(
		deepProgram(deepSizes{chain: 3, calls: 1, unary: 1, logic: 4}),
		"check(",
	) - 1
}

// bigDeep is deepProgram's program at bigSizes, checked once for every
// test that needs it, since checking it takes a while.
var bigDeep struct {
	prog *ast.Program
	once sync.Once
}

// bigDeepProgram returns deepProgram's program at bigSizes, checked.
func bigDeepProgram(t *testing.T) *ast.Program {
	t.Helper()
	bigDeep.once.Do(func() {
		start := time.Now()
		bigDeep.prog = compileWithStd(t, deepProgram(bigSizes))
		t.Logf("checked in %v", time.Since(start))
	})
	if bigDeep.prog == nil {
		t.Fatal("deepProgram(bigSizes) did not check")
	}
	return bigDeep.prog
}

// optLevels are the ways TestDeepExpressionsExampleRuns builds the
// example: every optimization level, and with the address and undefined
// behavior sanitizers, every finding fatal.
var optLevels = [][]string{
	{"-O0"},
	{"-O1"},
	{"-O2"},
	{"-O3"},
	{"-Os"},
	{"-Oz"},
	{"-O1", "-fsanitize=address,undefined", "-fno-sanitize-recover=all"},
}

// TestDeepExpressionsExampleRuns builds examples/deep-expressions each way
// optLevels says and checks every check it prints passes.
func TestDeepExpressionsExampleRuns(t *testing.T) {
	src := readFile(t, filepath.Join("..", "..", "examples", "deep-expressions", "main.tck"))
	prog := compileWithStd(t, src)
	for _, flags := range optLevels {
		t.Run(strings.Join(flags, " "), func(t *testing.T) {
			runChecks(t, buildProgram(t, prog, "", flags...), deepChecks())
		})
	}
}

// TestDeepExpressionsExampleIsGenerated checks examples/deep-expressions
// is deepProgram's program at exampleSizes, which -update rewrites it to.
func TestDeepExpressionsExampleIsGenerated(t *testing.T) {
	path := filepath.Join("..", "..", "examples", "deep-expressions", "main.tck")
	want := deepProgram(exampleSizes)
	if *update {
		writeFile(t, path, want)
	}
	if got := readFile(t, path); got != want {
		t.Errorf("%s is not deepProgram(exampleSizes); run go test ./codegen/c -run %s -update",
			path, t.Name())
	}
}

// TestDeepExpressionsRun builds deepProgram's program at bigSizes, far
// past what C's parser could take before, at -O0, -O2 and with the
// address and undefined behavior sanitizers, every finding fatal, and
// checks every check passes: clang sees no expression nested deeper than
// it can parse, and the values, wrapping and order are Tack's. Every
// other level is built from the example (see
// TestDeepExpressionsExampleRuns).
func TestDeepExpressionsRun(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a large program three times")
	}
	prog := bigDeepProgram(t)
	for _, flags := range [][]string{
		{"-O0"},
		{"-O2"},
		{"-O1", "-fsanitize=address,undefined", "-fno-sanitize-recover=all"},
	} {
		t.Run(strings.Join(flags, " "), func(t *testing.T) {
			start := time.Now()
			bin := buildProgram(t, prog, "", flags...)
			t.Logf("built in %v", time.Since(start))
			runChecks(t, bin, deepChecks())
		})
	}
}

// TestDeepExpressionsStayShallow checks the C written for deepProgram's
// program, at bigSizes, nests no expression deeper than a bound well
// within what C promises, while its source nests them thousands of levels
// deep, and that writing it stays quick.
func TestDeepExpressionsStayShallow(t *testing.T) {
	prog := bigDeepProgram(t)
	start := time.Now()
	out, diags := c.New().Generate(prog, stdtest.MustBuiltins())
	if len(diags) > 0 {
		t.Fatalf("generate reported %+v", diags)
	}
	elapsed := time.Since(start)
	t.Logf("generated in %v", elapsed)
	if elapsed > 10*time.Second {
		t.Errorf("generating took %v", elapsed)
	}
	if depth, line := deepestLine(string(out)); depth > 48 {
		t.Errorf("C nests %d levels deep, at line %d", depth, line)
	}
}

// deepestLine returns how deeply src, C, nests its parentheses and
// brackets within one statement, the deepest, and the line it is on.
// Braces are left out: they nest statements, which this does not bound.
func deepestLine(src string) (deepest, line int) {
	depth, at := 0, 1
	for i := 0; i < len(src); i++ {
		switch src[i] {
		case '(', '[':
			depth++
			if depth > deepest {
				deepest, line = depth, at
			}
		case ')', ']':
			depth--
		case '\n':
			at++
		case '"', '\'':
			q := src[i]
			for i++; i < len(src) && src[i] != q; i++ {
				if src[i] == '\\' {
					i++
				}
			}
		}
	}
	return deepest, line
}
