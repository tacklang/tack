// checkDrift checks each file portCorpusDivergences allows to differ,
// but those portCorpusUnchecked lists, against the reference Go
// compiler, env.goBin, run on the
// port's std: a golden must be the stage line ok, ---, and what its
// program's --emit writes, and a tack.h copy what --emit-header writes
// there, so that the drift is the port's std alone and not the port's
// compiler. Each run is in a fresh temporary directory holding a copy of
// the program's directory below examples/, its tack.h copies removed,
// and of the port's std at src/std, TACK_HOME that directory, as the
// port's tools/corpus runs it. An entry of portCorpusUnchecked that
// portCorpusDivergences does not list fails, so the list cannot go
// stale. It runs only as TestPortFiles does.
func checkDrift(t *testing.T) {
	t.Helper()
	paths := make([]string, 0, len(portCorpusDivergences))
	for p := range portCorpusDivergences {
		if _, unchecked := portCorpusUnchecked[p]; !unchecked {
			paths = append(paths, p)
		}
	}
	for p := range portCorpusUnchecked {
		if _, listed := portCorpusDivergences[p]; !listed {
			t.Errorf("%s is listed in portCorpusUnchecked, but not in portCorpusDivergences: drop it", p)
		}
	}
	sort.Strings(paths)
	for _, p := range paths {
		rel := strings.TrimPrefix(p, portCorpusDir+"/")
		var top, flag, compared string
		switch {
		case strings.HasPrefix(rel, "golden/") && strings.HasSuffix(rel, ".c.golden"):
			top = strings.TrimSuffix(strings.TrimPrefix(rel, "golden/"), ".c.golden")
			flag = "--emit"
		case strings.HasPrefix(rel, "examples/") && path.Base(rel) == "tack.h":
			top, _, _ = strings.Cut(strings.TrimPrefix(rel, "examples/"), "/")
			flag, compared = "--emit-header", rel
		default:
			t.Errorf("%s is neither a golden nor a tack.h copy, which the reference compiler writes: "+
				"list it in portCorpusUnchecked, with the reason it cannot be checked", p)
			continue
		}
		if strings.Contains(top, "_") {
			t.Errorf("%s: checkDrift cannot tell which program the golden %s is", p, top)
			continue
		}
		got := referenceOutput(t, top, flag, compared)
		want, err := os.ReadFile(filepath.Join(env.home, filepath.FromSlash(p))) //nolint:gosec // G304: the port's corpus
		if err != nil {
			t.Fatal(err)
		}
		if flag == "--emit" {
			got = "stage: ok\n---\n" + got
		}
		if d := firstDiffLabeled("reference Go", "port", []byte(got), want); d != "" {
			t.Errorf("%s is not what the reference Go compiler's %s writes on the port's std: %s", p, flag, d)
		}
	}
}

// referenceOutput runs the reference Go compiler's flag, --emit or
// --emit-header, on the program of examples/top, in a fresh copy of it
// and of the port's std (see checkDrift), and returns its standard
// output for --emit, or the bytes of compared, a path below the copy's
// root, which --emit-header wrote, for --emit-header. The program is
// built from its directory when it holds a tack.mod or several Tack
// files, and as its main.tck alone otherwise, as the harness's
// findExamples builds it.
func referenceOutput(t *testing.T, top, flag, compared string) string {
	t.Helper()
	dir := t.TempDir()
	ex := filepath.Join(dir, "examples", top)
	if err := copyTree(filepath.Join(env.home, portCorpusDir, "examples", top), ex); err != nil {
		t.Fatal(err)
	}
	if err := removeHeaders(ex); err != nil {
		t.Fatal(err)
	}
	if err := copyTree(homeStd(), filepath.Join(dir, "src", "std")); err != nil {
		t.Fatal(err)
	}
	target := "examples/" + top
	tcks, err := filepath.Glob(filepath.Join(ex, "*.tck"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(ex, "tack.mod")); err != nil && len(tcks) == 1 && filepath.Base(tcks[0]) == "main.tck" {
		target += "/main.tck"
	}
	in := input{name: top, dir: dir, env: []string{"TACK_HOME=" + dir, "TMPDIR=" + t.TempDir()}}
	r := runCompiler(t, env.goBin, env.goCache, in, []string{flag, target})
	if r.code != 0 {
		t.Fatalf("the reference Go compiler's %s %s: exit status %d\n%s", flag, target, r.code, r.stderr)
	}
	if flag == "--emit" {
		return string(r.stdout)
	}
	data, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(compared))) //nolint:gosec // G304: the copy's file
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// caseRecords returns the recorded standard error of every entry of
// testdata/divergences.txtar, by its id, for compareCorpus.
func caseRecords() (map[string]string, error) {
	list, err := loadedDivergences()
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, d := range list {
		out[d.id] = string(d.want.stderr)
	}
	return out, nil
}

// sameCase reports whether a and b hold the same files, in the same
// order, and the same expected section.
func sameCase(a, b archiveCase) bool {
	if a.expected != b.expected || len(a.files) != len(b.files) {
		return false
	}
	for i := range a.files {
		if a.files[i] != b.files[i] {
			return false
		}
	}
	return true
}

// caseDiff says how port, a case of the port's corpus, differs from
// frozen, this module's: the first line that differs of its expected
// section, or that its files do.
func caseDiff(frozen, port archiveCase) string {
	if frozen.expected != port.expected {
		return "expected: " + firstDiffLabeled("frozen", "port", []byte(frozen.expected), []byte(port.expected))
	}
	for i := range frozen.files {
		if i >= len(port.files) || frozen.files[i] != port.files[i] {
			return "its files differ, from " + frozen.files[i][0]
		}
	}
	return "the port's has more files"
}

// TestCompareCorpus checks compareCorpus, which TestPortFiles runs, on
// two small corpora laid out as the real ones are: matching ones pass,
// with the port's tack.mod left out as portCorpusOnly leaves it; a case
// allowed to differ passes when only its expected section differs, and,
// held to a record, when that section is the record with its warnings
// left out; and each change below fails them: a case that differs, one
// only the port has, a differing comment, a case allowed that does not
// differ, one allowed that neither has, one allowed whose program
// differs, one allowed whose expected section is not its record's, or
// whose record is missing, a golden that differs, an extra file below
// examples/, and a stray file elsewhere below corpus/. It needs no port
// and runs either way.
func TestCompareCorpus(t *testing.T) {
	const archive = "a comment\n-- a/main.tck --\npackage main\n-- a/expected --\nstage: codegen\n---\n\nx: error: e\n\n"
	type change struct {
		name         string
		port, frozen map[string]string
		allowedCases map[string]string
		records      map[string]string
		want         int
	}
	same := map[string]string{"examples/invalid.txtar": archive, "golden/a.golden": "g\n"}
	with := func(over map[string]string) map[string]string {
		out := map[string]string{}
		for k, v := range same {
			out[k] = v
		}
		for k, v := range over {
			out[k] = v
		}
		return out
	}
	differ := strings.Replace(archive, "x: error: e", "y: error: f", 1)
	program := strings.Replace(archive, "package main\n", "package main\n\n", 1)
	allowed := map[string]string{"invalid.txtar#a": "id: a reason"}
	record := map[string]string{"id": "\nw: warning: v\n01 |\tx\n\ny: error: f\n\nz: warning: u\n\n"}
	cases := []change{
		{"matching", same, same, nil, nil, 0},
		{"case differs", with(map[string]string{"examples/invalid.txtar": differ}), same, nil, nil, 1},
		{"case differs, allowed", with(map[string]string{"examples/invalid.txtar": differ}), same, allowed, nil, 0},
		{"case differs, allowed, as recorded", with(map[string]string{"examples/invalid.txtar": differ}), same,
			allowed, record, 0},
		{"case differs, allowed, not as recorded", with(map[string]string{"examples/invalid.txtar": differ}), same,
			allowed, map[string]string{"id": "\ny: error: g\n\n"}, 1},
		{"case differs, allowed, no record", with(map[string]string{"examples/invalid.txtar": differ}), same,
			allowed, map[string]string{"other": "\n"}, 1},
		{"program differs, allowed", with(map[string]string{"examples/invalid.txtar": program}), same, allowed, nil, 1},
		{"allowed but same", same, same, allowed, nil, 1},
		{"allowed but absent", same, same, map[string]string{"invalid.txtar#b": "id: a reason"}, nil, 1},
		{"port-only case", with(map[string]string{"examples/invalid.txtar": archive +
			"-- b/main.tck --\npackage main\n-- b/expected --\nstage: parse\n---\nz\n"}), same, nil, nil, 1},
		{"comment differs", with(map[string]string{"examples/invalid.txtar": "another" + archive[1:]}), same, nil, nil, 1},
		{"golden differs", with(map[string]string{"golden/a.golden": "h\n"}), same, nil, nil, 1},
		{"extra file", with(map[string]string{"examples/x/main.tck": "package main\n"}), same, nil, nil, 1},
		{"stray file", with(map[string]string{"notes.txt": "x\n"}), same, nil, nil, 1},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			port, frozen := t.TempDir(), t.TempDir()
			writeAll := func(root string, files map[string]string, frozenSide bool) {
				t.Helper()
				for p, data := range files {
					if frozenSide && strings.HasPrefix(p, "golden/") {
						p = "test/testdata/" + strings.TrimPrefix(p, "golden/")
					} else if !frozenSide {
						p = portCorpusDir + "/" + p
					}
					full := filepath.Join(root, filepath.FromSlash(p))
					mustDo(t, os.MkdirAll(filepath.Dir(full), 0o750))
					mustDo(t, os.WriteFile(full, []byte(data), 0o600))
				}
			}
			writeAll(port, c.port, false)
			writeAll(frozen, c.frozen, true)
			mustDo(t, os.WriteFile(filepath.Join(port, portCorpusDir, "tack.mod"), []byte("module corpus\n"), 0o600))
			files, err := corpusFiles(port, frozen, portCorpusOnly)
			if err != nil {
				t.Fatal(err)
			}
			msgs := compareCorpus(port, frozen, files, nil, c.allowedCases, c.records)
			msgs = append(msgs, checkPortOnly(port, portCorpusOnly, "portCorpusOnly")...)
			if len(msgs) != c.want {
				t.Errorf("got %d failures, want %d: %q", len(msgs), c.want, msgs)
			}
		})
	}
}

// TestWithoutWarnings checks withoutWarnings, which compareCorpus holds
// an allowed case's expected section to its record with: it drops each
// warning's block, its source lines with it, wherever it is, and keeps
// every error's.
func TestWithoutWarnings(t *testing.T) {
	in := "\na: warning: w\n01 |\tx\n   |\t^\n\nb: error: e\n02 |\ty\n\nc: warning: v\n\nd: error: f\n\n"
	want := "\nb: error: e\n02 |\ty\n\nd: error: f\n\n"
	if got := withoutWarnings(in); got != want {
		t.Errorf("withoutWarnings gave %q, want %q", got, want)
	}
}
