// corpusFiles returns every file of the port's corpus in portRoot with
// the file of this module's corpus in frozenRoot it is compared with,
// sorted by the port's path: each regular file below portCorpusDir/examples
// in the port or below examples in this module, at the same path below
// each, and each below portCorpusDir/golden in the port or below
// test/testdata in this module, likewise; but for the port's files
// portOnly lists. Every other file below portCorpusDir is paired with
// the same path in this module, which has none, so a stray file there
// fails too, as does a file one tree has and the other has not.
func corpusFiles(portRoot, frozenRoot string, portOnly map[string]string) ([]portFile, error) {
	pairs := [][2]string{
		{portCorpusDir + "/examples", "examples"},
		{portCorpusDir + "/golden", "test/testdata"},
	}
	paths := map[string]string{}
	port, err := treeFiles(portRoot, portCorpusDir)
	if err != nil {
		return nil, err
	}
	for _, p := range port {
		paths[p] = p
		for _, pair := range pairs {
			if rest, ok := strings.CutPrefix(p, pair[0]+"/"); ok {
				paths[p] = pair[1] + "/" + rest
			}
		}
	}
	for _, pair := range pairs {
		frozen, err := treeFiles(frozenRoot, pair[1])
		if err != nil {
			return nil, err
		}
		for _, p := range frozen {
			paths[pair[0]+strings.TrimPrefix(p, pair[1])] = p
		}
	}
	for p := range portOnly {
		delete(paths, p)
	}
	out := make([]portFile, 0, len(paths))
	for port, frozen := range paths {
		out = append(out, portFile{port: port, frozen: frozen})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].port < out[j].port })
	return out, nil
}

// isArchive reports whether f is one of the corpus's txtar archives,
// directly in examples/, whose cases compareCorpus compares one by one.
func isArchive(f portFile) bool {
	return path.Dir(f.frozen) == "examples" && path.Ext(f.frozen) == ".txtar"
}

// compareCorpus compares files, the port's corpus in portRoot with
// this module's in frozenRoot, as corpusFiles pairs them, and returns a
// message for each failure: each archive case by case (see
// compareArchive), with cases allowed to differ, held to records, and
// every other file as comparePortFiles compares them, with files allowed
// to differ. records maps a divergence's id to its recorded standard
// error (see caseRecords); nil checks no case against a record.
func compareCorpus(portRoot, frozenRoot string, files []portFile, allowedFiles, allowedCases, records map[string]string) []string {
	var plain []portFile
	var msgs []string
	seen := map[string]bool{}
	for _, f := range files {
		if !isArchive(f) {
			plain = append(plain, f)
			continue
		}
		msgs = append(msgs, compareArchive(portRoot, frozenRoot, f, allowedCases, records, seen)...)
	}
	msgs = append(msgs, comparePortFiles(portRoot, frozenRoot, plain, allowedFiles, "portCorpusDivergences")...)
	stale := make([]string, 0, len(allowedCases))
	for k := range allowedCases {
		if !seen[k] {
			stale = append(stale, k)
		}
	}
	sort.Strings(stale)
	for _, k := range stale {
		msgs = append(msgs, fmt.Sprintf("case %s is allowed to differ, but neither archive has it: drop it from portCaseDivergences", k))
	}
	return msgs
}

// archiveCase is one case of an archive as compareArchive compares it:
// its files, each a name and its bytes, in archive order, the single
// format's program as main.tck, and its expected section.
type archiveCase struct {
	files    [][2]string
	expected string
}

// readArchive reads the archive at p, in the single format when its base
// name is invalid.txtar or warnings.txtar and the tree format otherwise,
// as internal/invalid reads them, and returns its comment and its cases,
// by name.
func readArchive(p string) (string, map[string]archiveCase, error) {
	data, err := os.ReadFile(p) //nolint:gosec // G304: an archive of either corpus
	if err != nil {
		return "", nil, err
	}
	out := map[string]archiveCase{}
	switch filepath.Base(p) {
	case "invalid.txtar", "warnings.txtar":
		comment, cases, err := invalid.Parse(data)
		if err != nil {
			return "", nil, fmt.Errorf("%s: %w", p, err)
		}
		for _, c := range cases {
			out[c.Name] = archiveCase{files: [][2]string{{"main.tck", string(c.Source)}}, expected: string(c.Expected)}
		}
		return string(comment), out, nil
	}
	comment, cases, err := invalid.ParseTree(data)
	if err != nil {
		return "", nil, fmt.Errorf("%s: %w", p, err)
	}
	for _, c := range cases {
		ac := archiveCase{expected: string(c.Expected)}
		for _, f := range c.Files {
			ac.files = append(ac.files, [2]string{f.Path, string(f.Data)})
		}
		out[c.Name] = ac
	}
	return string(comment), out, nil
}

// compareArchive compares f, an archive of the port's corpus in portRoot
// and this module's in frozenRoot, case by case, and returns a message
// for each failure: an archive one side cannot read, a comment that
// differs, a case one side has and the other has not, a case whose files
// or expected section differ and that allowed, the cases allowed to
// differ, keyed as portCaseDivergences keys them, does not hold, a case
// allowed that does not differ, and one allowed that differs other than
// as it may (see allowedDiff). It sets seen for each key of a case
// either side has.
func compareArchive(portRoot, frozenRoot string, f portFile, allowed, records map[string]string, seen map[string]bool) []string {
	portComment, port, err := readArchive(filepath.Join(portRoot, filepath.FromSlash(f.port)))
	if err != nil {
		return []string{fmt.Sprintf("%s: %v", f.port, err)}
	}
	frozenComment, frozen, err := readArchive(filepath.Join(frozenRoot, filepath.FromSlash(f.frozen)))
	if err != nil {
		return []string{fmt.Sprintf("%s: %v", f.frozen, err)}
	}
	var msgs []string
	if d := firstDiffLabeled("frozen", "port", []byte(frozenComment), []byte(portComment)); d != "" {
		msgs = append(msgs, fmt.Sprintf("%s's comment differs from this module's frozen %s: %s", f.port, f.frozen, d))
	}
	names := map[string]bool{}
	for n := range port {
		names[n] = true
	}
	for n := range frozen {
		names[n] = true
	}
	sorted := make([]string, 0, len(names))
	for n := range names {
		sorted = append(sorted, n)
	}
	sort.Strings(sorted)
	base := path.Base(f.frozen)
	for _, n := range sorted {
		key := base + "#" + n
		seen[key] = true
		p, inPort := port[n]
		g, inFrozen := frozen[n]
		reason, ok := allowed[key]
		switch {
		case !inPort || !inFrozen:
			msgs = append(msgs, fmt.Sprintf("case %s is in one archive only (port %t, frozen %t)", key, inPort, inFrozen))
		case !sameCase(p, g) && !ok:
			msgs = append(msgs, fmt.Sprintf("case %s differs from this module's frozen %s: %s", key, f.frozen, caseDiff(g, p)))
		case sameCase(p, g) && ok:
			msgs = append(msgs, fmt.Sprintf("case %s is allowed to differ, but does not: drop it from portCaseDivergences", key))
		case ok:
			if msg := allowedDiff(key, reason, g, p, records); msg != "" {
				msgs = append(msgs, msg)
			}
		}
	}
	return msgs
}

// allowedDiff returns why port, the port's copy of the case key, which
// portCaseDivergences allows to differ from frozen, this module's, for
// reason, differs other than as it may, or "": only its expected section
// may differ, and, with records, it must be what the harness renders of
// the divergence's record whose id starts reason: frozen's stage line and
// ---, then the record's standard error with its warnings left out (see
// withoutWarnings), since the harness renders a case the backend rejects
// with the backend's diagnostics alone, where the record is the driver's
// output, the stages' warnings among them.
func allowedDiff(key, reason string, frozen, port archiveCase, records map[string]string) string {
	if !sameCase(archiveCase{files: frozen.files}, archiveCase{files: port.files}) {
		return fmt.Sprintf("case %s may differ only in its expected section, but its files differ: %s",
			key, caseDiff(archiveCase{files: frozen.files}, archiveCase{files: port.files}))
	}
	if records == nil {
		return ""
	}
	id, _, _ := strings.Cut(reason, ":")
	rec, ok := records[id]
	if !ok {
		return fmt.Sprintf("case %s is allowed for the divergence %s, which testdata/divergences.txtar does not record", key, id)
	}
	header, _, found := strings.Cut(frozen.expected, "\n---\n")
	if !found {
		return fmt.Sprintf("case %s: this module's expected section has no stage line", key)
	}
	want := header + "\n---\n" + withoutWarnings(rec)
	if d := firstDiffLabeled("record", "port", []byte(want), []byte(port.expected)); d != "" {
		return fmt.Sprintf("case %s's expected section is not the divergence %s's record, its warnings left out: %s", key, id, d)
	}
	return ""
}

// withoutWarnings returns rendered, diagnostics as the driver renders
// them, a blank line and then each followed by one, without the
// diagnostics that are warnings, each a block whose first line says
// ": warning: ".
func withoutWarnings(rendered string) string {
	body, ok := strings.CutPrefix(rendered, "\n")
	if !ok {
		return rendered
	}
	var kept []string
	for _, block := range strings.SplitAfter(body, "\n\n") {
		first, _, _ := strings.Cut(block, "\n")
		if !strings.Contains(first, ": warning: ") {
			kept = append(kept, block)
		}
	}
	return "\n" + strings.Join(kept, "")
}

