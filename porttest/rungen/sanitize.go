// sanFamily reports whether fn, a test of codegen/c, is one of batch 2's:
// a test that builds an example, or a program of its own, with its own
// clang flags, the sanitizers most often, and runs it.
func sanFamily(fn string) bool {
	for _, s := range []string{"IsSanitizerClean", "AreSanitizerClean", "ExampleRuns", "RunUnderSanitizers",
		"RunsAtEveryLevel", "CallOnceAndRunClean", "ExamplesAreSanitizerClean"} {
		if strings.HasSuffix(fn, s) {
			return true
		}
	}
	return false
}

