const sanDefine = "-D_DEFAULT_SOURCE"

// sanLoopFlags undo, for every record of batch 2, the two loop flags the
// driver passes to every compile and codegen/c's tests leave out on
// purpose (see buildCWith there), as nearly as clang's flags allow:
// -fno-finite-loops by -ffinite-loops, a later one of the pair winning,
// and -mllvm -indvars-predicate-loops=false by its default, true, a later
// -mllvm value winning. -ffinite-loops is not C11's default, which no
// flag restores: it also takes a while or do loop of a constant
// condition, as while (1), to be finite, which C11 does not, though a
// for (;;) neither (measured by clang's llvm.loop.mustprogress marks at
// -O0). No C batch 2's records compile, emitted or written, holds such a
// loop now; one that did would be compiled with an assumption its test's
// build does not make.
var sanLoopFlags = []string{"-ffinite-loops", "-mllvm", "-indvars-predicate-loops=true"}

