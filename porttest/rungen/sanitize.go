// what clang compiles rather than what it warns of, which every record of
// batch 2 passes as the test does.
var sanStrictFlags = []string{"-fstrict-flex-arrays=3"}

// sanValue is a value the reader of batch 2's tests computes: a string,
// an int64, a list of strings or of lists, a file of examples/ the test
// reads, a program it compiles or builds, or a row of a table.
type sanValue any

// sanFile is a file of examples/, by its path below the module's root.
type sanFile struct{ path string }

// sanSource is a program's source as a test hands it to a build: a file
// of examples/, a directory of examples/ the loader reads whole, or
// source the test holds.
type sanSource struct {
	file   string // a path below the module's root, as examples/x/main.tck
	dir    string // a directory of examples/, as examples/x
	inline string
}

// sanEnviron is append(os.Environ(), kv...): the variables a run adds.
type sanEnviron []string

// sanBuilder is a strings.Builder a test reports a run's standard error
// with, and sanCmd a command of a binary it runs.
type sanBuilder struct{}

// sanCmd is exec.Command(bin) of a test, before it runs, and the
// variables it adds to the environment.
type sanCmd struct {
	bin sanBin
	env []string
}

// sanBin is a binary a test built: from what source, with what C file,
// a file of examples/ or source the test holds, its clang flags, and
// whether it compiles the C files of its packages, std's and the
// example's, with -D_DEFAULT_SOURCE, as buildProgram, which buildWithStd
// and buildWithStdAndC build through, does and buildExternWith and
// buildWith do not.
type sanBin struct {
	src     sanSource
	cfile   string
	cinline string
	flags   []string
	define  bool
}

// sanOut is a stream of a run of bin a test compares: stdout or code.
type sanOut struct {
	bin  sanBin
	what string
}

// sanLeaf is one leaf of a test: its name, the binary it runs and what it
// asserts of the run, as record lines but the build's.
type sanLeaf struct {
	name   string
	bin    *sanBin
	env    []string
	exit   *int64
	stdout *sanValue
	checks []string
}

// sanReader interprets one test of batch 2.
type sanReader struct {
	s      *source
	fn     string
	err    error
	leaves []*sanLeaf
}

// stop records why the test cannot be read, the first reason only, and
// panics to unwind to read, which recovers.
func (r *sanReader) stop(format string, a ...any) {
	if r.err == nil {
		r.err = fmt.Errorf("%s: %s: "+format, append([]any{r.s.path, r.fn}, a...)...)
	}
	panic(r)
}

// sanCases returns batch 2's records of the test fd of s, or an error that
// says what in it rungen does not read.
func sanCases(s *source, fd *ast.FuncDecl) (recs []record, err error) {
	r := &sanReader{s: s, fn: fd.Name.Name}
	func() {
		defer func() {
			if p := recover(); p != nil && p != r {
				panic(p)
			}
		}()
		env := map[string]sanValue{}
		root := &sanLeaf{}
		r.block(fd.Body.List, env, root)
		switch {
		case len(r.leaves) == 0 && root.bin != nil:
			r.finish(root, env, env)
		case root.bin != nil || root.exit != nil || len(root.checks) > 0:
			// A run at the top of the test beside subtests is no leaf the
			// inventory lists, and would be lost.
			r.stop("it runs a binary at its top level beside its subtests, which rungen does not read")
		}
	}()
	if r.err != nil {
		return nil, r.err
	}
	if len(r.leaves) == 0 {
		return nil, fmt.Errorf("%s: %s: no run rungen reads", s.path, fd.Name.Name)
	}
	return r.records()
}

// block interprets the statements of a test or a subtest, env its
// variables, leaf the subtest it is in, if any.
func (r *sanReader) block(stmts []ast.Stmt, env map[string]sanValue, leaf *sanLeaf) {
	for _, st := range stmts {
		r.stmt(st, env, leaf)
	}
}

// stmt interprets one statement.
func (r *sanReader) stmt(st ast.Stmt, env map[string]sanValue, leaf *sanLeaf) {
	switch x := st.(type) {
	case *ast.AssignStmt:
		r.assign(x, env, leaf)
	case *ast.DeclStmt:
		g := x.Decl.(*ast.GenDecl)
		vs, ok := g.Specs[0].(*ast.ValueSpec)
		if !ok || len(g.Specs) != 1 || len(vs.Names) != 1 || len(vs.Values) != 0 {
			r.stop("it declares what rungen does not read")
		}
		switch exprString(vs.Type) {
		case "strings.Builder":
			// A builder a run's standard error goes to, for a failure's
			// report.
			env[vs.Names[0].Name] = sanBuilder{}
		default:
			if at, ok := vs.Type.(*ast.ArrayType); ok && at.Len == nil && exprString(at.Elt) == "string" {
				env[vs.Names[0].Name] = []string(nil)
				break
			}
			r.stop("it declares a %s, which rungen does not read", exprString(vs.Type))
		}
	case *ast.IfStmt:
		r.ifStmt(x, env, leaf)
	case *ast.RangeStmt:
		list := r.eval(x.X, env, leaf)
		v, _ := x.Value.(*ast.Ident)
		if v == nil {
			r.stop("it ranges with no value variable")
		}
		for _, item := range r.items(list) {
			inner := maps(env)
			inner[v.Name] = item
			r.block(x.Body.List, inner, leaf)
			// The body runs in a copy, its own variables its own; one it
			// assigns of those around it would be lost, so it stops.
			for k, was := range env {
				if !reflect.DeepEqual(inner[k], was) {
					r.stop("a loop of it assigns to %s, a variable outside the loop, which rungen does not read", k)
				}
			}
		}
	case *ast.ExprStmt:
		call, ok := x.X.(*ast.CallExpr)
		if !ok {
			r.stop("it evaluates %s for nothing", exprString(x.X))
		}
		r.call(call, env, leaf)
	default:
		r.stop("it has a %T, which rungen does not read", st)
	}
}

// maps returns a copy of env, for a loop's or a subtest's own variables.
func maps(env map[string]sanValue) map[string]sanValue {
	out := map[string]sanValue{}
	for k, v := range env {
		out[k] = v
	}
	return out
}

// items returns the elements of v, a list a test ranges over.
func (r *sanReader) items(v sanValue) []sanValue {
	switch l := v.(type) {
	case []string:
		out := make([]sanValue, len(l))
		for i, s := range l {
			out[i] = s
		}
		return out
	case [][]string:
		out := make([]sanValue, len(l))
		for i, s := range l {
			out[i] = s
		}
		return out
	case []map[string]sanValue:
		out := make([]sanValue, len(l))
		for i, s := range l {
			out[i] = s
		}
		return out
	}
	r.stop("it ranges over %T, which rungen does not read", v)
	return nil
}

// assign interprets an assignment, := or =, of known values.
func (r *sanReader) assign(x *ast.AssignStmt, env map[string]sanValue, leaf *sanLeaf) {
	if len(x.Rhs) != 1 {
		r.stop("it assigns several values at once")
	}
	if call, ok := x.Rhs[0].(*ast.CallExpr); ok && len(x.Lhs) == 2 {
		a, b := r.call2(call, env, leaf)
		r.set(x.Lhs[0], a, env)
		r.set(x.Lhs[1], b, env)
		return
	}
	if len(x.Lhs) != 1 {
		r.stop("it assigns %d values from one", len(x.Lhs))
	}
	r.set(x.Lhs[0], r.eval(x.Rhs[0], env, leaf), env)
}

// set binds e, a variable or _, to v; cmd.Stderr = &b, of a builder b, is
// a run's standard error kept for a failure's report, and binds nothing.
func (r *sanReader) set(e ast.Expr, v sanValue, env map[string]sanValue) {
	if sel, ok := e.(*ast.SelectorExpr); ok {
		cmd, isCmd := env[exprString(sel.X)].(*sanCmd)
		if isCmd && sel.Sel.Name == "Stderr" {
			if _, ok := v.(sanBuilder); ok {
				return
			}
		}
		if isCmd && sel.Sel.Name == "Env" {
			if add, ok := v.(sanEnviron); ok {
				cmd.env = append(cmd.env, add...)
				return
			}
		}
		r.stop("it sets %s, which rungen does not read", exprString(sel))
	}
	id, ok := e.(*ast.Ident)
	if !ok {
		r.stop("it assigns to %s, which rungen does not read", exprString(e))
	}
	if id.Name != "_" {
		env[id.Name] = v
	}
}

// ifStmt interprets an if: one on known values runs the branch it takes;
// any other is an assertion, its condition's parts read into leaf, and
// its branch, the failure's report, is not run.
func (r *sanReader) ifStmt(x *ast.IfStmt, env map[string]sanValue, leaf *sanLeaf) {
	if x.Init != nil {
		r.stmt(x.Init, env, leaf)
	}
	if v, ok := r.known(x.Cond, env); ok {
		// A branch assigns to the variables around it, as csrc = ...
		// does, so it runs in them.
		if v {
			r.block(x.Body.List, env, leaf)
		} else if x.Else != nil {
			if b, ok := x.Else.(*ast.BlockStmt); ok {
				r.block(b.List, env, leaf)
			} else {
				r.stop("it has an else if, which rungen does not read")
			}
		}
		return
	}
	if x.Else != nil {
		r.stop("an assertion of it has an else, which rungen does not read")
	}
	for _, atom := range conditionAtoms(x.Cond, r.stop) {
		r.assertion(atom, env, leaf)
	}
}

// known evaluates c when it compares known strings, reporting whether it
// does.
func (r *sanReader) known(c ast.Expr, env map[string]sanValue) (bool, bool) {
	b, ok := c.(*ast.BinaryExpr)
	if !ok || (b.Op != token.NEQ && b.Op != token.EQL) {
		return false, false
	}
	if id, ok := b.X.(*ast.Ident); ok && exprString(b.Y) == "nil" {
		if v, bound := env[id.Name]; bound && v == nil {
			return b.Op == token.EQL, true
		}
	}
	x, okX := r.tryString(b.X, env)
	y, okY := r.tryString(b.Y, env)
	if !okX || !okY {
		return false, false
	}
	return (x == y) == (b.Op == token.EQL), true
}

// tryString returns e's value when it is a known string: a literal, a
// constant or a variable holding one.
func (r *sanReader) tryString(e ast.Expr, env map[string]sanValue) (string, bool) {
	switch x := e.(type) {
	case *ast.BasicLit:
		if x.Kind == token.STRING {
			return r.s.eval(x, nil).(string), true
		}
	case *ast.Ident:
		if v, ok := env[x.Name].(string); ok {
			return v, true
		}
	case *ast.SelectorExpr:
		if row, ok := env[exprString(x.X)].(map[string]sanValue); ok {
			if v, ok := row[x.Sel.Name].(string); ok {
				return v, true
			}
		}
	}
	return "", false
}

// assertion reads one part of a test's condition into leaf, as builtReader
// does for batch 1, or stops.
func (r *sanReader) assertion(atom ast.Expr, env map[string]sanValue, leaf *sanLeaf) {
	switch x := atom.(type) {
	case *ast.CallExpr:
		switch {
		case isSel(x.Fun, "errors", "As"):
			return
		case isSel(x.Fun, "strings", "Contains") && len(x.Args) == 2:
			if r.str(x.Args[1], env) != "FAIL" {
				r.stop("it tests %s, which rungen does not read", exprString(x))
			}
			switch v := r.evalQuiet(x.Args[0], env).(type) {
			case sanFile:
				env["\x00guard"] = v
				return
			case sanOut:
				if v.what == "stdout" && leaf != nil {
					r.useBin(v.bin, leaf)
					line := "lacks stdout " + q("FAIL")
					if !slices.Contains(leaf.checks, line) {
						leaf.checks = append(leaf.checks, line)
					}
					return
				}
			}
			r.stop("it tests %s, which rungen does not read", exprString(x))
		}
	case *ast.BinaryExpr:
		if x.Op != token.NEQ {
			break
		}
		for _, side := range [2][2]ast.Expr{{x.X, x.Y}, {x.Y, x.X}} {
			lhs := exprString(side[0])
			switch {
			case lhs == "err" && exprString(side[1]) == "nil":
				if leaf != nil && env["err"] == "run" {
					zero := int64(0)
					leaf.exit = &zero
				}
				return
			}
			if o, ok := r.evalQuiet(side[0], env).(sanOut); ok && leaf != nil {
				r.compare(o, side[1], env, leaf)
				return
			}
			if call, ok := side[0].(*ast.CallExpr); ok && isSel(call.Fun, "strings", "Count") && len(call.Args) == 2 && leaf != nil {
				o, isOut := r.evalQuiet(call.Args[0], env).(sanOut)
				if !isOut || o.what != "stdout" {
					r.stop("it counts in %s, which rungen does not read", exprString(call.Args[0]))
				}
				r.useBin(o.bin, leaf)
				leaf.checks = append(leaf.checks, fmt.Sprintf("count stdout %d %s", r.int(side[1], env), q(r.str(call.Args[1], env))))
				return
			}
		}
	}
	r.stop("it asserts %s, which rungen does not read", exprString(atom))
}

// evalQuiet is eval of e when e is a variable or string(variable), and nil
// otherwise, never stopping.
func (r *sanReader) evalQuiet(e ast.Expr, env map[string]sanValue) sanValue {
	switch x := e.(type) {
	case *ast.Ident:
		return env[x.Name]
	case *ast.CallExpr:
		if id, ok := x.Fun.(*ast.Ident); ok && id.Name == "string" && len(x.Args) == 1 {
			return r.evalQuiet(x.Args[0], env)
		}
	}
	return nil
}

// compare reads into leaf what a test compares o, a run's stream or
// status, with: want.
func (r *sanReader) compare(o sanOut, want ast.Expr, env map[string]sanValue, leaf *sanLeaf) {
	r.useBin(o.bin, leaf)
	switch o.what {
	case "code":
		v := r.int(want, env)
		leaf.exit = &v
	case "stdout":
		v := r.eval(want, env, leaf)
		switch v.(type) {
		case string, sanFile:
		default:
			r.stop("it compares standard output with %T, which rungen does not read", v)
		}
		leaf.stdout = &v
	default:
		r.stop("it compares %s, which rungen does not read", o.what)
	}
}

// useBin makes bin leaf's binary, or stops when leaf runs another.
func (r *sanReader) useBin(bin sanBin, leaf *sanLeaf) {
	if leaf.bin == nil {
		b := bin
		leaf.bin = &b
		return
	}
	if !sameBin(*leaf.bin, bin) {
		r.stop("a subtest of it runs two binaries, which rungen does not read")
	}
}

// sameBin reports whether a and b are one build.
func sameBin(a, b sanBin) bool {
	return a.src == b.src && a.cfile == b.cfile && a.cinline == b.cinline && slices.Equal(a.flags, b.flags) && a.define == b.define
}

// str evaluates e, a string.
func (r *sanReader) str(e ast.Expr, env map[string]sanValue) string {
	v, ok := r.eval(e, env, nil).(string)
	if !ok {
		r.stop("%s is no string rungen reads", exprString(e))
	}
	return v
}

// int evaluates e, an int.
func (r *sanReader) int(e ast.Expr, env map[string]sanValue) int64 {
	v, ok := r.eval(e, env, nil).(int64)
	if !ok {
		r.stop("%s is no int rungen reads", exprString(e))
	}
	return v
}

// eval evaluates e to a sanValue, stopping on what it does not read.
func (r *sanReader) eval(e ast.Expr, env map[string]sanValue, leaf *sanLeaf) sanValue {
	switch x := e.(type) {
	case *ast.BasicLit:
		return r.s.eval(x, nil)
	case *ast.ParenExpr:
		return r.eval(x.X, env, leaf)
	case *ast.Ident:
		if v, ok := env[x.Name]; ok {
			return v
		}
		if x.Name == "nil" {
			return nil
		}
		if v, ok := r.topLevel(x.Name); ok {
			return r.eval(v, map[string]sanValue{}, nil)
		}
		r.stop("it uses %s, which rungen does not read", x.Name)
	case *ast.SelectorExpr:
		if row, ok := env[exprString(x.X)].(map[string]sanValue); ok {
			if v, ok := row[x.Sel.Name]; ok {
				return v
			}
		}
		r.stop("it uses %s, which rungen does not read", exprString(x))
	case *ast.BinaryExpr:
		a, b := r.eval(x.X, env, leaf), r.eval(x.Y, env, leaf)
		as, okA := a.(string)
		bs, okB := b.(string)
		if x.Op == token.ADD && okA && okB {
			return as + bs
		}
		ai, okA := a.(int64)
		bi, okB := b.(int64)
		if okA && okB {
			switch x.Op {
			case token.ADD:
				return ai + bi
			case token.SUB:
				return ai - bi
			}
		}
		r.stop("it computes %s, which rungen does not read", exprString(x))
	case *ast.CompositeLit:
		return r.composite(x, env, leaf)
	case *ast.UnaryExpr:
		if x.Op == token.AND {
			if b, ok := r.eval(x.X, env, leaf).(sanBuilder); ok {
				return b
			}
		}
	case *ast.CallExpr:
		return r.call(x, env, leaf)
	}
	r.stop("it uses %s, which rungen does not read", exprString(e))
	return nil
}

// topLevel returns the value of the top-level variable or constant name
// of the test's package, from any of its files.
func (r *sanReader) topLevel(name string) (ast.Expr, bool) {
	if v, ok := topLevel(r.s, name); ok {
		return v, true
	}
	for _, f := range packageFiles(r.s.path) {
		if v, ok := topLevel(src(f), name); ok {
			return v, true
		}
	}
	return nil, false
}

// packageFiles returns the test files of the directory of p, a Go file
// below the module's root.
func packageFiles(p string) []string {
	names, err := filepath.Glob(filepath.Join(path.Dir(p), "*_test.go"))
	if err != nil {
		fail(err)
	}
	sort.Strings(names)
	return names
}

// composite evaluates a literal list of strings, of lists, or a table of
// structs.
func (r *sanReader) composite(x *ast.CompositeLit, env map[string]sanValue, leaf *sanLeaf) sanValue {
	switch t := x.Type.(type) {
	case *ast.ArrayType:
		switch elt := t.Elt.(type) {
		case *ast.Ident:
			if elt.Name == "string" {
				var out []string
				for _, e := range x.Elts {
					out = append(out, r.str(e, env))
				}
				return out
			}
		case *ast.ArrayType:
			var out [][]string
			for _, e := range x.Elts {
				c, ok := e.(*ast.CompositeLit)
				if !ok {
					l, isList := r.eval(e, env, leaf).([]string)
					if !isList {
						r.stop("a list of lists of it holds %s", exprString(e))
					}
					out = append(out, l)
					continue
				}
				c.Type = elt
				out = append(out, r.composite(c, env, leaf).([]string))
			}
			return out
		case *ast.StructType:
			names := structFields(t)
			var out []map[string]sanValue
			for _, e := range x.Elts {
				row := map[string]sanValue{}
				for i, f := range e.(*ast.CompositeLit).Elts {
					if kv, ok := f.(*ast.KeyValueExpr); ok {
						row[kv.Key.(*ast.Ident).Name] = r.eval(kv.Value, env, leaf)
					} else {
						row[names[i]] = r.eval(f, env, leaf)
					}
				}
				out = append(out, row)
			}
			return out
		}
	}
	r.stop("it uses a literal %s, which rungen does not read", exprString(x.Type))
	return nil
}

// call evaluates or runs a call of a test: the helpers of codegen/c's
// tests rungen knows, filepath.Join, append and t.Run.
func (r *sanReader) call(x *ast.CallExpr, env map[string]sanValue, leaf *sanLeaf) sanValue {
	arg := func(i int) sanValue { return r.eval(x.Args[i], env, leaf) }
	switch {
	case isSel(x.Fun, "t", "Run") && len(x.Args) == 2:
		name := r.str(x.Args[0], env)
		fn, ok := x.Args[1].(*ast.FuncLit)
		if !ok {
			r.stop("t.Run of %s, which rungen does not read", exprString(x.Args[1]))
		}
		r.subtest(name, fn, env, leaf, nil)
		return nil
	case isCall(x, "atO0Too") && len(x.Args) == 3:
		flags, ok := arg(1).([]string)
		fn, okFn := x.Args[2].(*ast.FuncLit)
		if !ok || !okFn {
			r.stop("atO0Too of what rungen does not read")
		}
		runs := [][]string{flags}
		if i := slices.IndexFunc(flags, isLevel); i >= 0 && flags[i] != "-O0" {
			o0 := slices.Clone(flags)
			o0[i] = "-O0"
			runs = [][]string{o0, flags}
		}
		for _, run := range runs {
			level := "-O0"
			if i := slices.IndexFunc(run, isLevel); i >= 0 {
				level = run[i]
			}
			r.subtest(level, fn, env, leaf, run)
		}
		return nil
	case isSel(x.Fun, "t", "Helper"):
		return nil
	case isSel(x.Fun, "t", "Fatal"), isSel(x.Fun, "t", "Fatalf"), isSel(x.Fun, "t", "Errorf"):
		// A report is reached only in an assertion's body, which read does
		// not run, or in a branch rungen evaluates: a test that fails there
		// whatever it runs is no test rungen reads.
		r.stop("it reports a failure in a branch rungen takes, %s", exprString(x))
	case isSel(x.Fun, "t", "Skipf"), isSel(x.Fun, "t", "Skip"):
		// A skip in a branch rungen evaluates would skip the test, or a
		// subtest, on a condition rungen knows: the record would hold a run
		// the test never makes.
		r.stop("it skips in a branch rungen takes, %s", exprString(x))
	case isSel(x.Fun, "filepath", "Join"):
		var parts []string
		for i := range x.Args {
			switch v := arg(i).(type) {
			case string:
				parts = append(parts, v)
			case []string:
				if x.Ellipsis == token.NoPos || i != len(x.Args)-1 {
					r.stop("filepath.Join of a list not spread")
				}
				parts = append(parts, v...)
			default:
				r.stop("filepath.Join of %T", v)
			}
		}
		return filepath.Join(parts...)
	case isSel(x.Fun, "strings", "Join") && len(x.Args) == 2:
		l, ok := arg(0).([]string)
		if !ok {
			r.stop("strings.Join of no list")
		}
		return strings.Join(l, r.str(x.Args[1], env))
	case isCall(x, "append") && len(x.Args) >= 2 && exprString(x.Args[0]) == "os.Environ()" && x.Ellipsis == token.NoPos:
		var add sanEnviron
		for i := 1; i < len(x.Args); i++ {
			add = append(add, r.str(x.Args[i], env))
		}
		return add
	case isCall(x, "string") && len(x.Args) == 1:
		switch v := arg(0).(type) {
		case string, sanOut, sanFile:
			return v
		}
		r.stop("string of what rungen does not read")
	case isCall(x, "append") && x.Ellipsis != token.NoPos && len(x.Args) == 2:
		a, okA := arg(0).([]string)
		b, okB := arg(1).([]string)
		if !okA || !okB {
			r.stop("append of what rungen does not read")
		}
		return append(slices.Clone(a), b...)
	case isCall(x, "readFile") && len(x.Args) == 2:
		return sanFile{r.examplePath(r.str(x.Args[1], env))}
	case isSel(x.Fun, "exec", "Command") && len(x.Args) >= 1:
		bin, ok := arg(0).(sanBin)
		if !ok {
			r.stop("it runs %s, which rungen does not read", exprString(x))
		}
		if len(x.Args) > 1 {
			// Only a spread list of no arguments, as runBig's with no
			// input, is read.
			l, isList := arg(1).([]string)
			if len(x.Args) != 2 || x.Ellipsis == token.NoPos || !isList || len(l) > 0 {
				r.stop("it runs %s with arguments, which rungen does not read", exprString(x))
			}
		}
		return &sanCmd{bin: bin}
	case isCall(x, "compileExampleDir") && len(x.Args) == 2:
		return sanSource{dir: "examples/" + r.str(x.Args[1], env)}
	case isCall(x, "compileWithStd") && len(x.Args) == 2:
		return r.source(arg(1))
	case isCall(x, "buildWithStd") || isCall(x, "buildWith"):
		bin := r.build(r.source(arg(1)), nil, x, 2, env, leaf)
		bin.define = isCall(x, "buildWithStd")
		return bin
	case isCall(x, "buildWithStdAndC") || isCall(x, "buildExternWith"):
		c := arg(2)
		bin := r.build(r.source(arg(1)), c, x, 3, env, leaf)
		bin.define = isCall(x, "buildWithStdAndC")
		return bin
	case isCall(x, "buildProgram") && len(x.Args) >= 3:
		prog, ok := arg(1).(sanSource)
		if !ok {
			r.stop("buildProgram of no program rungen reads")
		}
		bin := r.build(prog, arg(2), x, 3, env, leaf)
		bin.define = true
		return bin
	case isCall(x, "runChecks") || isCall(x, "runRegionChecks"):
		if leaf == nil || len(x.Args) != 3 {
			r.stop("%s outside a subtest rungen reads", exprString(x.Fun))
		}
		bin, ok := arg(1).(sanBin)
		if !ok {
			r.stop("%s of no binary rungen reads", exprString(x.Fun))
		}
		r.useBin(bin, leaf)
		zero := int64(0)
		leaf.exit = &zero
		leaf.checks = append(leaf.checks, "lacks stdout "+q("FAIL"),
			fmt.Sprintf("count stdout %d %s", r.int(x.Args[2], env), q(" ok\n")))
		if isCall(x, "runRegionChecks") {
			leaf.env = append(leaf.env, r.helperEnv("leakChecked"))
		}
		return nil
	case isCall(x, "runExample") || isCall(x, "checkWrites"):
		if leaf == nil {
			r.stop("%s outside a subtest rungen reads", exprString(x.Fun))
		}
		bin, ok := arg(1).(sanBin)
		if !ok {
			r.stop("%s of no binary rungen reads", exprString(x.Fun))
		}
		r.useBin(bin, leaf)
		zero := int64(0)
		leaf.exit = &zero
		if isCall(x, "checkWrites") {
			v := arg(2)
			leaf.stdout = &v
			return nil
		}
		return sanOut{bin, "stdout"}
	}
	if fd := r.helper(x); fd != nil && fd.Type.Results == nil {
		r.helperCall(fd, x, env, leaf)
		return nil
	}
	if fd := r.helper(x); fd != nil && fd.Type.Results != nil && fd.Type.Results.NumFields() == 1 {
		inner := r.bindParams(fd, x, env, leaf)
		for _, st := range fd.Body.List {
			if ret, ok := st.(*ast.ReturnStmt); ok && len(ret.Results) == 1 {
				return r.eval(ret.Results[0], inner, leaf)
			}
			r.stmt(st, inner, leaf)
		}
		r.stop("%s returns nothing rungen reads", fd.Name.Name)
	}
	r.stop("it calls %s, which rungen does not read", exprString(x.Fun))
	return nil
}

// helperCall interprets a helper of no result, as a test's own body, its
// parameters the call's arguments, in the leaf of the call.
func (r *sanReader) helperCall(fd *ast.FuncDecl, x *ast.CallExpr, env map[string]sanValue, leaf *sanLeaf) {
	inner := r.bindParams(fd, x, env, leaf)
	r.block(fd.Body.List, inner, leaf)
}

// bindParams returns the variables of fd, a helper x calls: each
// parameter but t bound to its argument's value.
func (r *sanReader) bindParams(fd *ast.FuncDecl, x *ast.CallExpr, env map[string]sanValue, leaf *sanLeaf) map[string]sanValue {
	inner := map[string]sanValue{}
	i := 0
	for _, f := range fd.Type.Params.List {
		for _, n := range f.Names {
			if i >= len(x.Args) {
				r.stop("%s takes more than it is given", fd.Name.Name)
			}
			if n.Name != "t" {
				inner[n.Name] = r.eval(x.Args[i], env, leaf)
			}
			i++
		}
	}
	return inner
}

// call2 evaluates a call of two results: exampleFiles, a helper returning
// a program's source and its C, runStatus, a run's output and status, and
// exec.Command(bin).Output(), its output and error.
func (r *sanReader) call2(x *ast.CallExpr, env map[string]sanValue, leaf *sanLeaf) (sanValue, sanValue) {
	switch {
	case isCall(x, "exampleFiles") && len(x.Args) == 3:
		dir := r.str(x.Args[1], env)
		return sanFile{"examples/" + dir + "/main.tck"}, sanFile{"examples/" + dir + "/" + r.str(x.Args[2], env)}
	case isCall(x, "runStatus") && len(x.Args) == 2:
		bin, ok := r.eval(x.Args[1], env, leaf).(sanBin)
		if !ok || leaf == nil {
			r.stop("runStatus of no binary rungen reads")
		}
		r.useBin(bin, leaf)
		return sanOut{bin, "stdout"}, sanOut{bin, "code"}
	case isSel(x.Fun, "exec", "LookPath"):
		return "clang", nil
	case isCall(x, "Output") || isCall(x, "CombinedOutput"):
		sel, ok := x.Fun.(*ast.SelectorExpr)
		if !ok || len(x.Args) != 0 {
			break
		}
		cmd, ok := r.eval(sel.X, env, leaf).(*sanCmd)
		if !ok || leaf == nil {
			r.stop("it runs %s, which rungen does not read", exprString(sel.X))
		}
		bin := cmd.bin
		r.useBin(bin, leaf)
		for _, kv := range cmd.env {
			if !slices.Contains(leaf.env, kv) {
				leaf.env = append(leaf.env, kv)
			}
		}
		env["err"] = "run"
		if isCall(x, "CombinedOutput") {
			return nil, "run"
		}
		return sanOut{bin, "stdout"}, "run"
	case isSel(x.Fun, "os", "ReadFile") && len(x.Args) == 1:
		return sanFile{r.examplePath(r.str(x.Args[0], env))}, nil
	}
	if fd := r.helper(x); fd != nil {
		return r.helperCall2(fd, x, env, leaf)
	}
	r.stop("it calls %s for two values, which rungen does not read", exprString(x.Fun))
	return nil, nil
}

// helper returns the declaration of a function of the test's package that
// x calls, when it is one.
func (r *sanReader) helper(x *ast.CallExpr) *ast.FuncDecl {
	id, ok := x.Fun.(*ast.Ident)
	if !ok {
		return nil
	}
	for _, f := range packageFiles(r.s.path) {
		for _, d := range src(f).file.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv == nil && fd.Name.Name == id.Name {
				return fd
			}
		}
	}
	return nil
}

// helperCall2 interprets a helper of two results, its body assignments
// and one return, its parameters the call's arguments.
func (r *sanReader) helperCall2(fd *ast.FuncDecl, x *ast.CallExpr, env map[string]sanValue, leaf *sanLeaf) (sanValue, sanValue) {
	inner := r.bindParams(fd, x, env, leaf)
	for _, st := range fd.Body.List {
		switch y := st.(type) {
		case *ast.ReturnStmt:
			if len(y.Results) != 2 {
				r.stop("%s returns no two values rungen reads", fd.Name.Name)
			}
			return r.eval(y.Results[0], inner, leaf), r.eval(y.Results[1], inner, leaf)
		case *ast.ExprStmt:
			if c, ok := y.X.(*ast.CallExpr); !ok || !isSel(c.Fun, "t", "Helper") {
				r.stop("%s does what rungen does not read", fd.Name.Name)
			}
		default:
			r.stmt(st, inner, leaf)
		}
	}
	r.stop("%s returns nothing rungen reads", fd.Name.Name)
	return nil, nil
}

// helperEnv returns the one NAME=value the helper fn, of the test's
// package, appends to os.Environ(), as leakChecked does.
func (r *sanReader) helperEnv(fn string) string {
	for _, f := range packageFiles(r.s.path) {
		for _, d := range src(f).file.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Name.Name != fn || len(fd.Body.List) != 1 {
				continue
			}
			ret, ok := fd.Body.List[0].(*ast.ReturnStmt)
			if !ok || len(ret.Results) != 1 {
				break
			}
			call, ok := ret.Results[0].(*ast.CallExpr)
			if !ok || !isCall(call, "append") || len(call.Args) != 2 || exprString(call.Args[0]) != "os.Environ()" {
				break
			}
			return src(f).eval(call.Args[1], nil).(string)
		}
	}
	r.stop("%s gives no environment rungen reads", fn)
	return ""
}

// examplePath returns p, a path the test reads from codegen/c, as
// ../../examples/..., as the path below the module's root.
func (r *sanReader) examplePath(p string) string {
	rel, ok := strings.CutPrefix(filepath.ToSlash(p), "../../examples/")
	if !ok {
		r.stop("it reads %s, outside examples/", p)
	}
	return "examples/" + rel
}

// source returns v, what a test builds, as a program's source: a file of
// examples/ it read, or source it holds.
func (r *sanReader) source(v sanValue) sanSource {
	switch s := v.(type) {
	case sanFile:
		return sanSource{file: s.path}
	case sanSource:
		return s
	case string:
		return sanSource{inline: s}
	}
	r.stop("it builds %T, no source rungen reads", v)
	return sanSource{}
}

// build returns the binary a build helper call x makes of src and c, its
// flags the arguments from first on, spread or not.
func (r *sanReader) build(src sanSource, c sanValue, x *ast.CallExpr, first int, env map[string]sanValue, leaf *sanLeaf) sanBin {
	bin := sanBin{src: src}
	switch cv := c.(type) {
	case nil:
	case sanFile:
		bin.cfile = cv.path
	case string:
		if cv != "" {
			bin.cinline = cv
		}
	default:
		r.stop("it builds with a C file rungen does not read")
	}
	for i := first; i < len(x.Args); i++ {
		switch v := r.eval(x.Args[i], env, leaf).(type) {
		case string:
			bin.flags = append(bin.flags, v)
		case []string:
			if x.Ellipsis == token.NoPos || i != len(x.Args)-1 {
				r.stop("it passes a list of flags not spread")
			}
			bin.flags = append(bin.flags, v...)
		default:
			r.stop("it passes %T as a flag", v)
		}
	}
	return bin
}

// subtest runs fn, a subtest named name of parent, the test's root when
// its name is empty, with flags, when atO0Too hands it them, as its
// parameter.
func (r *sanReader) subtest(name string, fn *ast.FuncLit, env map[string]sanValue, parent *sanLeaf, flags []string) {
	full := strings.ReplaceAll(name, " ", "_")
	if parent != nil && parent.name != "" {
		full = parent.name + "/" + full
	}
	leaf := &sanLeaf{name: full}
	inner := maps(env)
	params := fn.Type.Params.List
	if flags != nil {
		if len(params) != 2 || len(params[1].Names) != 1 {
			r.stop("atO0Too's function takes no flags rungen reads")
		}
		inner[params[1].Names[0].Name] = flags
	}
	before := len(r.leaves)
	r.block(fn.Body.List, inner, leaf)
	if len(r.leaves) > before {
		return
	}
	r.finish(leaf, inner, env)
}

// finish checks leaf, a subtest or the test itself that ran a binary,
// its variables inner and those of what holds it outer, and adds it to
// the test's leaves: it must run a binary and assert its status, and a
// FAIL guard of either must be of the standard output it compares, a
// lacks line.
func (r *sanReader) finish(leaf *sanLeaf, inner, outer map[string]sanValue) {
	if leaf.bin == nil {
		r.stop("the subtest %s runs no binary rungen reads", leaf.name)
	}
	for _, e := range []map[string]sanValue{inner, outer} {
		guard, ok := e["\x00guard"].(sanFile)
		if !ok {
			continue
		}
		if leaf.stdout == nil || (*leaf.stdout) != sanValue(guard) {
			r.stop("it guards %s, which is no standard output it compares", guard.path)
		}
		if !slices.Contains(leaf.checks, "lacks stdout "+q("FAIL")) {
			leaf.checks = append(leaf.checks, "lacks stdout "+q("FAIL"))
		}
	}
	if leaf.exit == nil {
		r.stop("the subtest %s asserts no exit status rungen reads", leaf.name)
	}
	r.leaves = append(r.leaves, leaf)
}

// isLevel reports whether f is a -O flag, as codegen/c's tests' isLevel.
func isLevel(f string) bool {
	return strings.HasPrefix(f, "-O") && len(f) == 3
}

// records groups the test's leaves into records: those built from one
// source with the same flags but for the level, run with the same
// environment and asserting the same, are one record at each of their
// levels.
func (r *sanReader) records() ([]record, error) {
	type group struct {
		key    string
		leaves []*sanLeaf
		levels []string
	}
	var groups []*group
	byKey := map[string]*group{}
	for _, l := range r.leaves {
		level, cflags := "0", []string{}
		for _, f := range l.bin.flags {
			if isLevel(f) {
				level = strings.TrimPrefix(f, "-O")
			} else {
				cflags = append(cflags, f)
			}
		}
		key := fmt.Sprintf("%v|%s|%s|%v|%v|%v|%v|%v", l.bin.src, l.bin.cfile, l.bin.cinline, cflags, l.bin.define, l.env, *l.exit, l.checks)
		if l.stdout != nil {
			key += fmt.Sprintf("|%v", *l.stdout)
		}
		g, ok := byKey[key]
		if !ok {
			g = &group{key: key}
			byKey[key] = g
			groups = append(groups, g)
		}
		if slices.Contains(g.levels, level) {
			return nil, fmt.Errorf("%s: %s: two leaves of one build at -O%s", r.s.path, r.fn, level)
		}
		g.leaves = append(g.leaves, l)
		g.levels = append(g.levels, level)
	}
	var out []record
	for i, g := range groups {
		name := sanKebab(r.fn)
		if len(groups) > 1 {
			name += fmt.Sprintf("-%d", i+1)
		}
		rec, err := r.record(name, g.leaves, g.levels)
		if err != nil {
			return nil, err
		}
		out = append(out, rec)
	}
	return out, nil
}

// record returns the record of leaves, one build at each of levels.
func (r *sanReader) record(name string, leaves []*sanLeaf, levels []string) (record, error) {
	l := leaves[0]
	var lines []string
	for _, x := range leaves {
		if x.name == "" {
			lines = append(lines, "replaces "+r.s.path+" "+r.fn)
		} else {
			lines = append(lines, "replaces "+r.s.path+" "+r.fn+"/"+x.name)
		}
	}
	if l.bin.cinline != "" {
		lines = append(lines, "partial "+sanPartialC)
	}
	lines = append(lines, "strict-libs "+sanStrictLibs)
	var files [][2]string
	src := l.bin.src
	switch {
	case src.dir != "":
		if l.bin.cfile != "" || l.bin.cinline != "" {
			return record{}, fmt.Errorf("%s: %s: a directory built with a C file besides its own", r.s.path, r.fn)
		}
		lines = append(lines, "dir "+src.dir, "target .")
	case src.file != "":
		dir, base := path.Split(src.file)
		dir = strings.TrimSuffix(dir, "/")
		if l.bin.cinline != "" {
			return record{}, fmt.Errorf("%s: %s: an example built with C the test holds", r.s.path, r.fn)
		}
		cfiles, err := filepath.Glob(filepath.Join(dir, "*.c"))
		if err != nil {
			return record{}, err
		}
		var want []string
		if l.bin.cfile != "" {
			want = []string{filepath.FromSlash(l.bin.cfile)}
		}
		if !slices.Equal(cfiles, want) {
			return record{}, fmt.Errorf("%s: %s: %s holds the C files %v, and the test builds it with %v: the driver would build every one", r.s.path, r.fn, dir, cfiles, want)
		}
		lines = append(lines, "dir "+dir)
		if base != "main.tck" {
			lines = append(lines, "target "+base)
		}
	default:
		if l.bin.cfile != "" {
			return record{}, fmt.Errorf("%s: %s: source the test holds built with a C file of examples/", r.s.path, r.fn)
		}
		files = append(files, [2]string{"main.tck", src.inline})
		if l.bin.cinline != "" {
			files = append(files, [2]string{"helpers.c", l.bin.cinline})
		}
	}
	sort.Strings(levels)
	lines = append(lines, "opt "+strings.Join(sortLevels(levels), " "))
	cflags := slices.Clone(sanStrictFlags)
	for _, f := range l.bin.flags {
		if !isLevel(f) {
			cflags = append(cflags, f)
		}
	}
	if l.bin.define {
		cflags = append(cflags, sanDefine)
	}
	if slices.ContainsFunc(cflags, func(f string) bool {
		return strings.HasPrefix(f, "-fsanitize=") && slices.Contains(strings.Split(strings.TrimPrefix(f, "-fsanitize="), ","), "address")
	}) {
		cflags = append(cflags, sanASanDriver)
	}
	cflags = append(cflags, sanLoopFlags...)
	lines = append(lines, "cflags "+strings.Join(cflags, " "))
	for _, e := range l.env {
		lines = append(lines, "env "+q(e))
	}
	lines = append(lines, l.checks...)
	if l.stdout != nil {
		if f, ok := (*l.stdout).(sanFile); ok {
			lines = append(lines, "stdout-file "+f.path)
		}
	}
	lines = append(lines, fmt.Sprintf("exit %d", *l.exit))
	if l.stdout != nil {
		if s, ok := (*l.stdout).(string); ok {
			if s == "" {
				lines = append(lines, "stdout "+q(""))
			} else {
				lines = append(lines, chunks("stdout", s)...)
			}
		}
	}
	return record{name, files, lines}, nil
}

// sortLevels returns levels in codegen.Opts' order, 0 1 2 3 s z.
func sortLevels(levels []string) []string {
	order := "0123sz"
	out := slices.Clone(levels)
	sort.Slice(out, func(i, j int) bool { return strings.Index(order, out[i]) < strings.Index(order, out[j]) })
	return out
}

// sanKebab returns a test's name without Test, its words joined with
// dashes in lower case, as a record's name.
func sanKebab(fn string) string {
	var b strings.Builder
	for i, c := range strings.TrimPrefix(fn, "Test") {
		if c >= 'A' && c <= 'Z' {
			if i > 0 {
				b.WriteByte('-')
			}
			c += 'a' - 'A'
		}
		b.WriteRune(c)
	}
	return b.String()
}

// sanArchives returns batch 2's archives, one per test file of codegen/c
// with records, by name, codegen-c-<stem>.txtar, and the tests it could
// not read, each with why, for the caller to report.
func sanArchives() (map[string][]byte, map[string]string, error) {
	out := map[string][]byte{}
	unread := map[string]string{}
	for _, f := range packageFiles("codegen/c/gen_test.go") {
		f = filepath.ToSlash(f)
		s := src(f)
		var recs []record
		for _, d := range s.file.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv != nil || !strings.HasPrefix(fd.Name.Name, "Test") || !sanFamily(fd.Name.Name) {
				continue
			}
			if _, skip := sanSkipped[fd.Name.Name]; skip {
				continue
			}
			rs, err := sanCases(s, fd)
			if err != nil {
				unread[fd.Name.Name] = err.Error()
				continue
			}
			recs = append(recs, rs...)
		}
		if len(recs) == 0 {
			continue
		}
		stem := strings.ReplaceAll(strings.TrimSuffix(path.Base(f), "_test.go"), "_", "-")
		name := "codegen-c-" + stem + ".txtar"
		data, err := renderWith("Run records of "+f+"'s tests that build a program with clang flags\n"+
			"of their own and run it, written by tackc's porttest/rungen and completed\n"+
			"by tools/corpus --update; see tools/corpus/runs.tck for the format.\n", recs)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", name, err)
		}
		out[name] = data
	}
	return out, unread, nil
}

// sanSurvey writes, for rungen -survey, every test of batch 2's family
// rungen cannot read and why, to standard error.
func sanSurvey() {
	_, unread, err := sanArchives()
	if err != nil {
		fail(err)
	}
	names := make([]string, 0, len(unread))
	for n := range unread {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintln(os.Stderr, unread[n])
	}
}
