// builtCase is one record of batch 1 as builtCases reads it from a test:
// the leaves it replaces, the directory of examples/ it builds in and the
// target there, main.tck for example(name) and . for the directory, or
// the program a helper writes, the levels it builds at, none for the
// compiler's own, and what the test asserts of the run: its exit status,
// its standard output and error, as bytes or a file of examples/, and in
// checks its lacks and count lines.
type builtCase struct {
	name       string
	leaves     []string
	dir        string
	target     string
	program    string
	levels     []string
	notStrict  string
	exit       *int64
	stdout     *string
	stdoutFile string
	stderr     *string
	stderrFile string
	checks     []string
	partial    string
}

// builtRecords returns batch 1's records by archive name, from the
// TestBuilt tests of builtFiles but those builtSkipped names, levels
// from codegen.Opts, and stops rungen on a test it cannot read.
func builtRecords(opts []string) map[string][]record {
	out := map[string][]record{}
	for _, f := range builtFiles {
		s := src("tack/" + f)
		archive := "tack-" + strings.ReplaceAll(strings.TrimSuffix(f, "_test.go"), "_", "-") + ".txtar"
		for _, d := range s.file.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv != nil || !strings.HasPrefix(fd.Name.Name, "TestBuilt") {
				continue
			}
			if fd.Name.Name == "TestBuiltUnusedWarningsRuns" {
				out[archive] = append(out[archive], unusedWarningsCheck(s, fd))
			}
			if _, skip := builtSkipped[fd.Name.Name]; skip {
				continue
			}
			for _, c := range builtCases(s, fd, opts) {
				c.notStrict = builtNotStrict[fd.Name.Name]
				out[archive] = append(out[archive], c.record("tack/"+f, fd.Name.Name))
			}
		}
	}
	return out
}

// record returns the record of c, of the test fn of file.
func (c builtCase) record(file, fn string) record {
	var lines []string
	for _, l := range c.leaves {
		lines = append(lines, "replaces "+file+" "+l)
	}
	var files [][2]string
	if c.program != "" {
		files = [][2]string{{"main.tck", c.program}}
	} else {
		lines = append(lines, "dir examples/"+c.dir)
		if c.target != "main.tck" {
			lines = append(lines, "target "+c.target)
		}
	}
	if len(c.levels) > 0 {
		lines = append(lines, "opt "+strings.Join(c.levels, " "))
	}
	if c.notStrict != "" {
		lines = append(lines, "no-strict-c "+c.notStrict)
	}
	if c.partial != "" {
		lines = append(lines, "partial "+c.partial)
	}
	lines = append(lines, c.checks...)
	// The file lines come before the end, which tools/corpus --update
	// writes after every line it keeps.
	if c.stdoutFile != "" {
		lines = append(lines, "stdout-file examples/"+c.stdoutFile)
	}
	if c.stderrFile != "" {
		lines = append(lines, "stderr-file examples/"+c.stderrFile)
	}
	if c.exit != nil {
		lines = append(lines, "exit "+strconv.FormatInt(*c.exit, 10))
	}
	for _, st := range []struct {
		key string
		b   *string
	}{{"stdout", c.stdout}, {"stderr", c.stderr}} {
		switch {
		case st.b != nil && *st.b == "":
			lines = append(lines, st.key+" "+q(""))
		case st.b != nil:
			lines = append(lines, chunks(st.key, *st.b)...)
		}
	}
	return record{c.name, files, lines}
}

// unusedWarningsCheck returns the record of the --check half of the test
// fd, TestBuiltUnusedWarningsRuns: tack --check of the example, which
// must exit 0 with nothing on standard output and the warnings on
// standard error, which --update pins whole; the test's own want, the
// warnings it looks for, rungen reads and requires of the record with
// a note, as no record line says "contains". It says partial: the build
// half writes warnings too, and a record's build must be silent. Any
// other shape of the test stops rungen.
func unusedWarningsCheck(s *source, fd *ast.FuncDecl) record {
	var want []string
	var target string
	ast.Inspect(fd.Body, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.AssignStmt:
			if id, ok := x.Lhs[0].(*ast.Ident); ok && id.Name == "want" && len(x.Rhs) == 1 {
				lit, ok := x.Rhs[0].(*ast.CompositeLit)
				if !ok {
					fail(fmt.Errorf("%s: %s: its want is no literal list", s.path, fd.Name.Name))
				}
				for _, e := range lit.Elts {
					want = append(want, s.eval(e, nil).(string))
				}
			}
		case *ast.CallExpr:
			if isCall(x, "runTack") && len(x.Args) == 3 && exprString(x.Args[1]) == `"--check"` {
				call, ok := x.Args[2].(*ast.CallExpr)
				if !ok || !isCall(call, "example") {
					fail(fmt.Errorf("%s: %s: its --check target is no example", s.path, fd.Name.Name))
				}
				target = s.eval(call.Args[0], nil).(string)
			}
		}
		return true
	})
	if len(want) == 0 || target == "" {
		fail(fmt.Errorf("%s: %s: no want or no --check run rungen reads", s.path, fd.Name.Name))
	}
	lines := []string{"replaces " + s.path + " " + fd.Name.Name,
		"partial its build half is not held: the build writes warnings, and a record's build must be silent",
		"dir examples/" + target, "invoke " + q("--check"), "invoke " + q("main.tck")}
	for _, w := range want {
		lines = append(lines, "note the test requires standard error to hold "+q(w))
	}
	// The test's check that no error is among the warnings.
	lines = append(lines, "lacks stderr "+q("error"), "exit 0", "stdout "+q(""))
	return record{"unused-warnings-check", nil, lines}
}

// kebab returns a test's name without TestBuilt, or without Test for
// TestBuiltins, its words joined with dashes in lower case, as a
// record's name.
func kebab(fn string) string {
	var b strings.Builder
	stem := strings.TrimPrefix(fn, "TestBuilt")
	if strings.HasPrefix(fn, "TestBuiltins") {
		stem = strings.TrimPrefix(fn, "Test")
	}
	for i, r := range stem {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('-')
			}
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

// fileRef is what a local the test reads with os.ReadFile from
// filepath.Join(examplesDir, ...) stands for: that file, below examples/.
type fileRef string

// builtCases reads the records of the test fd of s: one for each row of
// the table it ranges over, or one, each built at every level of the
// loop over codegen.Opts, or a literal list of -O flags, it runs subtests
// in, or at the compiler's own.
func builtCases(s *source, fd *ast.FuncDecl, opts []string) []builtCase {
	locals := map[string]ast.Expr{}
	files := map[string]fileRef{}
	var table *ast.CompositeLit
	var tableVar string
	var levels, loopVals []string
	var optVar string
	var runName ast.Expr
	ast.Inspect(fd.Body, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.AssignStmt:
			if len(x.Rhs) != 1 {
				return true
			}
			if id, ok := x.Lhs[0].(*ast.Ident); ok && x.Tok == token.DEFINE {
				if call, ok := x.Rhs[0].(*ast.CallExpr); ok && isCall(call, "ReadFile") && len(call.Args) == 1 {
					files[id.Name] = fileRef(s.eval(call.Args[0], nil).(string))
				} else if len(x.Lhs) == 1 {
					locals[id.Name] = x.Rhs[0]
				}
			}
		case *ast.RangeStmt:
			v, _ := x.Value.(*ast.Ident)
			switch {
			case isSel(x.X, "codegen", "Opts"):
				levels, loopVals, optVar = opts, opts, v.Name
			case isOptFlags(x.X):
				optVar = v.Name
				for _, e := range x.X.(*ast.CompositeLit).Elts {
					flag := s.eval(e, nil).(string)
					levels, loopVals = append(levels, strings.TrimPrefix(flag, "-O")), append(loopVals, flag)
				}
			default:
				if c, ok := x.X.(*ast.CompositeLit); ok && v != nil {
					table, tableVar = c, v.Name
				}
			}
		case *ast.CallExpr:
			if isSel(x.Fun, "t", "Run") && len(x.Args) == 2 {
				runName = x.Args[0]
			}
		}
		return true
	})
	var rows []map[string]ast.Expr
	if table == nil {
		rows = []map[string]ast.Expr{{}}
	} else {
		names := structFields(table.Type)
		for _, el := range table.Elts {
			row := map[string]ast.Expr{}
			for i, f := range el.(*ast.CompositeLit).Elts {
				if kv, ok := f.(*ast.KeyValueExpr); ok {
					row[kv.Key.(*ast.Ident).Name] = kv.Value
				} else {
					row[names[i]] = f
				}
			}
			rows = append(rows, row)
		}
	}
	var out []builtCase
	for _, row := range rows {
		r := builtReader{s: s, locals: locals, files: files, row: row, tableVar: tableVar}
		c := builtCase{levels: levels}
		r.read(fd, &c)
		if c.dir == "" && c.program == "" {
			fail(fmt.Errorf("%s: %s builds no example rungen finds", s.path, fd.Name.Name))
		}
		c.name = kebab(fd.Name.Name)
		if table != nil {
			c.name += "-" + strings.ReplaceAll(r.str(row["name"], nil), " ", "-")
		}
		if runName == nil {
			c.leaves = []string{fd.Name.Name}
		} else {
			for _, l := range loopVals {
				leaf := r.str(runName, map[string]string{optVar: l})
				c.leaves = append(c.leaves, fd.Name.Name+"/"+strings.ReplaceAll(leaf, " ", "_"))
			}
		}
		out = append(out, c)
	}
	return out
}

// builtReader reads one row of a test: its locals, the files it reads
// and the row of its table, the table's variable tableVar.
type builtReader struct {
	s        *source
	locals   map[string]ast.Expr
	files    map[string]fileRef
	row      map[string]ast.Expr
	tableVar string
}

// resolve returns e with a local or the table's field it names replaced
// by its expression, as often as it names one.
func (r builtReader) resolve(e ast.Expr) ast.Expr {
	for i := 0; i < 8; i++ {
		switch x := e.(type) {
		case *ast.Ident:
			if v, ok := r.locals[x.Name]; ok {
				e = v
				continue
			}
			if v, ok := topLevel(r.s, x.Name); ok {
				if call, isCall := v.(*ast.CallExpr); isCall {
					e = call
					continue
				}
			}
		case *ast.SelectorExpr:
			if id, ok := x.X.(*ast.Ident); ok && id.Name == r.tableVar {
				if v, ok := r.row[x.Sel.Name]; ok {
					e = v
					continue
				}
			}
		case *ast.ParenExpr:
			e = x.X
			continue
		}
		return e
	}
	return e
}

// str evaluates e, a string, with vars the loop variables' values.
func (r builtReader) str(e ast.Expr, vars map[string]string) string {
	e = r.resolve(e)
	switch x := e.(type) {
	case *ast.Ident:
		if v, ok := vars[x.Name]; ok {
			return v
		}
	case *ast.CallExpr:
		if id, ok := x.Fun.(*ast.Ident); ok && id.Name == "string" && len(x.Args) == 1 {
			return r.str(x.Args[0], vars)
		}
	case *ast.BinaryExpr:
		if x.Op == token.ADD {
			return r.str(x.X, vars) + r.str(x.Y, vars)
		}
	}
	return r.s.eval(e, nil).(string)
}

// read sets in c what the test fd builds and asserts. Every condition
// of an if of the test must be one rungen knows, and every call that
// runs the built program one it reads whole; anything else stops rungen,
// naming the test and what it does not read, so no assertion of a test
// is dropped without a word:
//
//   - the build's checks, r.code != exitOK, r.stdout != "" and
//     r.stderr != "", which every record's build is held to;
//   - err != nil, on clang missing, a file the test reads, or the run's
//     own error, which says the run must exit 0;
//   - errors.As(err, &exitErr);
//   - the run's status, code or exitErr.ExitCode(), against a value,
//     either way round;
//   - its standard output, out or string(out), and its standard error,
//     errOut, against bytes or string(f) of a file of examples/ the test
//     read, either way round;
//   - strings.Contains(string(f), "FAIL") on such a file, the guard that
//     the expectation holds no FAIL: a lacks line;
//   - strings.Count(out, s) != n, either way round: a count line.
func (r builtReader) read(fd *ast.FuncDecl, c *builtCase) {
	name := fd.Name.Name
	stop := func(format string, a ...any) {
		fail(fmt.Errorf("%s: %s: "+format, append([]any{r.s.path, name}, a...)...))
	}
	runErr := map[string]bool{}
	exit0 := false
	var guards []fileRef
	ast.Inspect(fd.Body, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.AssignStmt:
			for _, l := range x.Lhs {
				if sel, ok := l.(*ast.SelectorExpr); ok {
					switch sel.Sel.Name {
					case "Stdin", "Stdout", "Stderr", "Env", "Dir", "ExtraFiles":
						stop("it sets %s of a command, which rungen does not read", exprString(sel))
					}
				}
			}
			if len(x.Rhs) == 1 {
				if call, ok := x.Rhs[0].(*ast.CallExpr); ok && (isCall(call, "Run") || isCall(call, "Output")) {
					if id, ok := x.Lhs[len(x.Lhs)-1].(*ast.Ident); ok {
						runErr[id.Name] = true
					}
				}
			}
		case *ast.CallExpr:
			switch {
			case isSel(x.Fun, "exec", "CommandContext") && len(x.Args) != 2,
				isSel(x.Fun, "exec", "Command") && len(x.Args) != 1:
				stop("it runs %s, arguments and all, which rungen does not read", exprString(x))
			case isCall(x, "runBuiltStreams") && (len(x.Args) != 3 || exprString(x.Args[2]) != "nil"):
				stop("it runs the program with an input, which rungen does not read")
			case isCall(x, "runBuiltArgs"), isCall(x, "runBuiltWithStdin"), isCall(x, "Chdir"), isCall(x, "Setenv"):
				stop("it calls %s, which rungen does not read", exprString(x.Fun))
			case isCall(x, "buildWithClang") && len(x.Args) == 2:
				c.dir, c.target = r.str(x.Args[1], nil), "main.tck"
			case isCall(x, "buildTargetWithClang") && len(x.Args) == 3:
				r.target(x.Args[2], c, stop)
			case isCall(x, "runTack") && len(x.Args) > 1:
				r.target(x.Args[len(x.Args)-1], c, stop)
			}
		case *ast.IfStmt:
			for _, atom := range conditionAtoms(x.Cond, stop) {
				r.condition(atom, c, runErr, &exit0, &guards, stop)
			}
		}
		return true
	})
	if c.exit == nil && exit0 {
		zero := int64(0)
		c.exit = &zero
	}
	if c.exit == nil {
		stop("it asserts no exit status rungen reads")
	}
	for _, f := range guards {
		line := "lacks " + r.streamOf(f, c, stop) + " " + q("FAIL")
		if !slicesContains(c.checks, line) {
			c.checks = append(c.checks, line)
		}
	}
}

// conditionAtoms returns the parts of e, an assertion's condition, that
// || joins: the test fails when any holds. A ! is read only before
// errors.As, the one negation an assertion of the tests holds, and a &&
// not at all, as an assertion's parts it joins fail only together; either
// elsewhere stops rungen, through stop, rather than read a part the wrong
// way round.
func conditionAtoms(e ast.Expr, stop func(string, ...any)) []ast.Expr {
	switch x := e.(type) {
	case *ast.ParenExpr:
		return conditionAtoms(x.X, stop)
	case *ast.UnaryExpr:
		if x.Op == token.NOT {
			if call, ok := x.X.(*ast.CallExpr); ok && isSel(call.Fun, "errors", "As") {
				return []ast.Expr{call}
			}
			stop("it asserts !%s, a negation rungen does not read", exprString(x.X))
		}
	case *ast.BinaryExpr:
		switch x.Op {
		case token.LOR:
			return append(conditionAtoms(x.X, stop), conditionAtoms(x.Y, stop)...)
		case token.LAND:
			stop("it asserts two conditions joined by &&, which rungen does not read")
		}
	}
	return []ast.Expr{e}
}

// condition reads one part of a test's condition, atom, into c, as read
// lists, a file it guards against FAIL into guards, for read to name its
// stream once the test is read, or stops rungen with stop.
func (r builtReader) condition(atom ast.Expr, c *builtCase, runErr map[string]bool, exit0 *bool, guards *[]fileRef, stop func(string, ...any)) {
	switch x := atom.(type) {
	case *ast.CallExpr:
		switch {
		case isSel(x.Fun, "errors", "As"):
			return
		case isSel(x.Fun, "strings", "Contains") && len(x.Args) == 2:
			f, ok := r.fileOf(x.Args[0])
			if !ok || r.str(x.Args[1], nil) != "FAIL" {
				stop("it tests %s, which rungen does not read", exprString(x))
			}
			*guards = append(*guards, f)
			return
		}
	case *ast.BinaryExpr:
		if x.Op != token.NEQ {
			break
		}
		for _, side := range [2][2]ast.Expr{{x.X, x.Y}, {x.Y, x.X}} {
			switch exprString(side[0]) {
			case "r.code", "r.stdout", "r.stderr":
				return
			case "err":
				if exprString(side[1]) == "nil" {
					if runErr["err"] {
						*exit0 = true
					}
					return
				}
			case "code", "exitErr.ExitCode()":
				v := r.int(side[1])
				c.exit = &v
				return
			case "out", "string(out)":
				r.stream(side[1], &c.stdout, &c.stdoutFile)
				return
			case "errOut":
				r.stream(side[1], &c.stderr, &c.stderrFile)
				return
			}
			if call, ok := side[0].(*ast.CallExpr); ok && isSel(call.Fun, "strings", "Count") && len(call.Args) == 2 {
				if exprString(call.Args[0]) != "out" && exprString(call.Args[0]) != "string(out)" {
					stop("it counts in %s, which rungen does not read", exprString(call.Args[0]))
				}
				c.checks = append(c.checks, fmt.Sprintf("count stdout %d %s", r.int(side[1]), q(r.str(call.Args[1], nil))))
				return
			}
		}
	}
	stop("it asserts %s, which rungen does not read", exprString(atom))
}

// fileOf returns the file of examples/ e, string(f), stands for, when f
// is a local the test read with os.ReadFile.
func (r builtReader) fileOf(e ast.Expr) (fileRef, bool) {
	if call, ok := e.(*ast.CallExpr); ok && isCall(call, "string") && len(call.Args) == 1 {
		if id, ok := call.Args[0].(*ast.Ident); ok {
			f, ok := r.files[id.Name]
			return f, ok
		}
	}
	return "", false
}

// streamOf returns the stream whose expectation the file f is: stdout or
// stderr, which the test compares it with, as c holds.
func (r builtReader) streamOf(f fileRef, c *builtCase, stop func(string, ...any)) string {
	switch string(f) {
	case c.stdoutFile:
		return "stdout"
	case c.stderrFile:
		return "stderr"
	}
	stop("it guards %s, which it compares with no stream rungen reads", f)
	return ""
}

// slicesContains reports whether l holds s.
func slicesContains(l []string, s string) bool {
	for _, x := range l {
		if x == s {
			return true
		}
	}
	return false
}

// target sets c's directory and target from e, a test's target:
// example(name), filepath.Join(examplesDir, name...), a directory, or a
// file a helper writes, program(t, body); anything else stops rungen.
func (r builtReader) target(e ast.Expr, c *builtCase, stop func(string, ...any)) {
	e = r.resolve(e)
	call, ok := e.(*ast.CallExpr)
	switch {
	case ok && isCall(call, "example") && len(call.Args) == 1:
		c.dir, c.target = r.str(call.Args[0], nil), "main.tck"
	case ok && isSel(call.Fun, "filepath", "Join") && len(call.Args) > 1 && exprString(call.Args[0]) == "examplesDir":
		p := r.s.eval(call, nil).(string)
		top, rest, _ := strings.Cut(p, "/")
		c.dir, c.target = top, "."
		if rest != "" {
			c.target = rest
		}
	case ok && isCall(call, "program") && len(call.Args) == 2:
		c.program = r.program(r.str(call.Args[1], nil))
	default:
		stop("it builds %s, a target rungen does not read", exprString(e))
	}
}

// program returns the source the test helper program(t, body) writes,
// read from the helper's own source.
func (r builtReader) program(body string) string {
	var lit ast.Expr
	ast.Inspect(src("tack/std_test.go").fn("program"), func(n ast.Node) bool {
		if call, ok := n.(*ast.CallExpr); ok && isCall(call, "writeSource") && len(call.Args) == 2 {
			if conv, ok := call.Args[1].(*ast.CallExpr); ok && len(conv.Args) == 1 {
				lit = conv.Args[0]
			}
		}
		return true
	})
	if lit == nil {
		fail(fmt.Errorf("tack/std_test.go: program writes no source rungen reads"))
	}
	return src("tack/std_test.go").eval(lit, map[string]any{"body": body}).(string)
}

// int evaluates e, an int.
func (r builtReader) int(e ast.Expr) int64 {
	e = r.resolve(e)
	return r.s.eval(e, nil).(int64)
}

// stream sets *b or *file from e, what a test compares a stream with:
// bytes, or string(x) of a file of examples/ the test read.
func (r builtReader) stream(e ast.Expr, b **string, file *string) {
	e = r.resolve(e)
	if f, ok := r.fileOf(e); ok {
		*file = string(f)
		return
	}
	v := r.str(e, nil)
	*b = &v
}

// topLevel returns the value of the top-level variable or constant name
// of s, and whether s declares one.
func topLevel(s *source, name string) (ast.Expr, bool) {
	for _, d := range s.file.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, sp := range g.Specs {
			if vs, ok := sp.(*ast.ValueSpec); ok {
				for i, n := range vs.Names {
					if n.Name == name && i < len(vs.Values) {
						return vs.Values[i], true
					}
				}
			}
		}
	}
	return nil, false
}

// isCall reports whether c calls a function or method named name.
func isCall(c *ast.CallExpr, name string) bool {
	switch f := c.Fun.(type) {
	case *ast.Ident:
		return f.Name == name
	case *ast.SelectorExpr:
		return f.Sel.Name == name
	}
	return false
}

// isSel reports whether e is pkg.name.
func isSel(e ast.Expr, pkg, name string) bool {
	s, ok := e.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	id, ok := s.X.(*ast.Ident)
	return ok && id.Name == pkg && s.Sel.Name == name
}

// isOptFlags reports whether e is a literal list of -O flags.
func isOptFlags(e ast.Expr) bool {
	c, ok := e.(*ast.CompositeLit)
	if !ok || len(c.Elts) == 0 {
		return false
	}
	for _, el := range c.Elts {
		l, ok := el.(*ast.BasicLit)
		if !ok || !strings.HasPrefix(l.Value, `"-O`) {
			return false
		}
	}
	return true
}

// exprString returns a short form of e: identifiers, selectors and calls
// of them, for matching what a comparison's left side is.
func exprString(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.Ident:
		return x.Name
	case *ast.SelectorExpr:
		return exprString(x.X) + "." + x.Sel.Name
	case *ast.CallExpr:
		var args []string
		for _, a := range x.Args {
			args = append(args, exprString(a))
		}
		return exprString(x.Fun) + "(" + strings.Join(args, ", ") + ")"
	case *ast.BasicLit:
		return x.Value
	}
	return fmt.Sprintf("%T", e)
}

// builtArchiveHeader is the comment of each archive of batch 1.
func builtArchiveHeader(file string) string {
	return "Run records of tack/" + file + "'s TestBuilt tests, written by tackc's\n" +
		"porttest/rungen and completed by tools/corpus --update; see\n" +
		"tools/corpus/runs.tck for the format.\n"
}

// builtArchives returns the archives of batch 1, by name, rendered.
func builtArchives(opts []string) (map[string][]byte, error) {
	out := map[string][]byte{}
	recs := builtRecords(opts)
	names := make([]string, 0, len(recs))
	for n := range recs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		file := strings.ReplaceAll(strings.TrimSuffix(strings.TrimPrefix(n, "tack-"), ".txtar"), "-", "_") + "_test.go"
		data, err := renderWith(builtArchiveHeader(file), recs[n])
		if err != nil {
			return nil, fmt.Errorf("%s: %w", n, err)
		}
		out[n] = data
	}
	return out, nil
}
