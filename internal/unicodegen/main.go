package main

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"unicode"
)

// class is one table generate writes: the name of its array in
// tables.tck, the Go predicate it is made from and that predicate's name,
// and what its doc comment says it holds.
type class struct {
	name   string
	is     func(rune) bool
	goName string
	what   string
}

// classes are the tables generate writes, in the order it writes them.
var classes = []class{
	{
		"print_runs",
		unicode.IsPrint,
		"unicode.IsPrint",
		"letters, marks, numbers, punctuation, symbols and U+0020",
	},
	{
		"graphic_runs",
		unicode.IsGraphic,
		"unicode.IsGraphic",
		"letters, marks, numbers, punctuation, symbols and spaces (Zs)",
	},
	{"letter_runs", unicode.IsLetter, "unicode.IsLetter", "letters (L)"},
	{"digit_runs", unicode.IsDigit, "unicode.IsDigit", "decimal digits (Nd)"},
	{
		"space_runs",
		unicode.IsSpace,
		"unicode.IsSpace",
		"White_Space: \\t \\n \\v \\f \\r, U+0020, U+0085, U+00A0 and others",
	},
}

// runs returns the runs of consecutive runes from 0 to unicode.MaxRune
// that is holds for, each as its first rune and its last, in ascending
// order.
func runs(is func(rune) bool) [][2]rune {
	var out [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !is(r) {
			continue
		}
		if n := len(out); n > 0 && out[n-1][1] == r-1 {
			out[n-1][1] = r
		} else {
			out = append(out, [2]rune{r, r})
		}
	}
	return out
}

// generate returns the contents of tables.tck.
func generate() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, `package unicode

// Code generated by internal/unicodegen from Go's unicode package, Unicode
// %s. DO NOT EDIT; run make unicode-tables instead.
`, unicode.Version)
	for _, c := range classes {
		rs := runs(c.is)
		fmt.Fprintf(
			&b,
			"\n// %s holds the runes %s holds for:\n// %s.\n// Its %d runs are each a first rune and a last, in ascending order.\n",
			c.name,
			c.goName,
			c.what,
			len(rs),
		)
		fmt.Fprintf(&b, "var %s = [%d]int32{\n", c.name, 2*len(rs))
		for i := 0; i < len(rs); i += 4 {
			b.WriteString("   ")
			for _, r := range rs[i:min(i+4, len(rs))] {
				fmt.Fprintf(&b, " 0x%04X, 0x%04X,", r[0], r[1])
			}
			b.WriteString("\n")
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

// main runs unicodegen with the process's arguments and exits with its
// status.
func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

// run writes the tables to the path args[0] names and returns the exit
// status.
func run(args []string, stderr io.Writer) int {
	if len(args) != 1 {
		_, _ = fmt.Fprintln(stderr, "usage: unicodegen <output.tck>")
		return 2
	}
	// The tables are a source file of the repository, readable by all.
	if err := os.WriteFile(args[0], generate(), 0o644); err != nil { //nolint:gosec // a source file
		_, _ = fmt.Fprintln(stderr, "unicodegen:", err)
		return 1
	}
	return 0
}
